var HAVE_KO = { y:['있음','y'], p:['부분','p'], n:['없음','n'] };

/* 화면 하나가 맡은 기능을 띠로 그립니다. 화면을 혼자 열어도 보이게. */
function featStrip(page) {
  var list = SCREEN_FEAT[page];
  if (!list || !list.length) return '';
  var n = { y:0, p:0, n:0 };
  list.forEach(function (f) { n[f[2]]++; });
  return '<section class="featbar">'
    + '<div class="fb-hd">'
      + '<span class="fb-k">이 화면이 맡는 기능</span>'
      + '<span class="fb-id">' + (SCREEN_ID[page] || '') + '</span>'
      + '<span class="fb-n">있음 ' + n.y + ' · 부분 ' + n.p + ' · 없음 ' + n.n + '</span>'
      + '<a class="fb-go" href="index.html">전체 대응표</a>'
    + '</div>'
    + '<div class="fb-list">' + list.map(function (f) {
        var m = FEAT[f[0]], h = HAVE_KO[f[2]];
        return '<div class="fb-r fb-' + h[1] + '">'
          + '<span class="fb-c">' + f[0] + '</span>'
          + '<span class="fb-t">' + m[1]
            + (f[1] === 'main' ? '<b class="fb-m">주</b>' : '')
            + '<span class="fb-s">' + f[3] + '</span></span>'
          + '<span class="fb-v">' + h[0] + '</span></div>';
      }).join('') + '</div>'
    + '</section>';
}

/* 화면 아래에 띠를 붙입니다. 각 화면 끝에서 한 번 부릅니다. */
function mountFeatures(page) {
  var el = document.createElement('div');
  el.innerHTML = featStrip(page);
  if (el.firstChild) document.body.appendChild(el.firstChild);
}
