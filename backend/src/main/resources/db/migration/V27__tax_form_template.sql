-- =============================================================================
-- 종합소득세 신고서 서식 템플릿 (P0-12 · API 14.3 · ERD 1.7)
--
-- 번호 주의 — 착수 시점(2026-09-15) develop 과 모든 원격 피쳐 브랜치를 훑어 V26 이
-- 최상단인 것을 확인하고 V27 을 잡았다. 오늘만 번호가 두 번 겹쳤다(V14·V18).
--
-- **서식 정의를 자바가 아니라 데이터로 둔다.** ERD 가 「서식 개정 시 데이터만 갱신한다」로
-- 정했다 — 별지 서식은 해마다 개정되는데 매핑표를 상수로 박으면 개정 때마다 재배포가 된다.
-- 귀속연도가 키에 들어가 있어 2027년 서식은 행을 하나 더 넣으면 된다.
--
-- **사업장 공용 기준 데이터다.** business_id 가 없다 — 서식은 나라가 정한 것이라
-- 사업장마다 다르지 않다.
--
-- 항목명·번호는 소득세법 시행규칙 **별지 제74호서식**(간편장부소득금액계산서, 개정
-- 2023.3.20)과 **제74호서식 부표**(총수입금액 및 필요경비명세서, 개정 2025.3.21) 원문을
-- 따른다. 본표와 부표는 번호가 겹친다(본표 ⑮ 총필요경비 / 부표 ⑮ 당기 상품매입액) —
-- 그래서 코드가 보는 열쇠는 번호가 아니라 field_key 이고, 번호는 label 안에만 있다.
-- =============================================================================

CREATE TABLE core.tax_form_template (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_type        VARCHAR(20)  NOT NULL,
    tax_year         INT          NOT NULL,
    name             VARCHAR(200) NOT NULL,
    official_form    VARCHAR(500),
    support_level    VARCHAR(20)  NOT NULL,

    -- ERD 표에 없는 컬럼이다. 14.3 의 서식 목록 응답이 eligibilityNote 를 요구하는데
    -- 담을 자리가 없었다 — 서식마다 다른 문구라 상수로 둘 수 없다. (ERD 이탈 기록 참고)
    eligibility_note VARCHAR(500),

    -- 섹션·필드 정의. [{sectionKey, label, fields:[{fieldKey, label, source, sensitive,
    -- formula, fixedValue, defaultValue}]}]
    sections         JSONB        NOT NULL,

    -- 거래 카테고리(8.1) → 서식 항목 매핑. {카테고리코드: {fieldKey|handling, note}}
    -- handling 이 있으면 항목에 더하지 않는다는 뜻이다(EXCLUDED·PENDING).
    category_mapping JSONB        NOT NULL DEFAULT '{}'::jsonb,

    -- AI 미전달·서버 미저장 필드 키. 조회 응답에서 값은 항상 null 이다.
    sensitive_fields JSONB        NOT NULL DEFAULT '[]'::jsonb,

    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_tft_form_year UNIQUE (form_type, tax_year),

    CONSTRAINT ck_tft_form_type CHECK (form_type IN (
        'SIMPLE_LEDGER', 'STANDARD_RATE', 'SIMPLE_RATE', 'DOUBLE_ENTRY')),

    -- DRAFT·DRAFT_OPTIONAL 만 초안을 만든다. 나머지 둘에 생성을 요청하면 400 이다(14.3).
    CONSTRAINT ck_tft_support_level CHECK (support_level IN (
        'DRAFT', 'DRAFT_OPTIONAL', 'GUIDE_ONLY', 'CHECKLIST_ONLY'))
);

COMMENT ON TABLE core.tax_form_template IS '종합소득세 신고서 서식 템플릿 (기준 데이터, 귀속연도별)';

