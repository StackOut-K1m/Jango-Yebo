-- =============================================================================
-- 1. 반복 패턴 cadence — BUSINESS_DAILY 추가
-- =============================================================================

-- 카드 정산은 '영업일마다 D+n 입금'이라 WEEKLY·MONTHLY·INTERVAL 어느 것으로도
-- 표현되지 않는다. 요식업 입금의 큰 축인데 반복 패턴으로 등록조차 되지 않아
-- 예측에서 통째로 빠진다(설계노트 G-2).
--
-- V1 정합 커밋(7c12064)이 ERD v1.9 반영분 중 이것만 빠뜨렸다. V1 헤더의
-- "범위에서 뺀 것" 목록에도 없으므로 결정이 아니라 누락이다.
--
-- CHECK 을 넓히는 방향이라 롤백이 깨지지 않는다 — 구버전 코드는 새 값을 쓰지 않는다.
-- 기존 행은 전부 통과하므로 재검증도 즉시 끝난다(현재 0행).
ALTER TABLE forecast.recurring_pattern DROP CONSTRAINT ck_rp_cadence;
ALTER TABLE forecast.recurring_pattern ADD CONSTRAINT ck_rp_cadence
    CHECK (cadence_type IN ('WEEKLY', 'MONTHLY', 'INTERVAL', 'BUSINESS_DAILY'));


-- =============================================================================
-- 2. 운영자금 안전선 (P1-08 → P0 승격)
-- =============================================================================

-- API 2.6 위험 등급 4단계 중 CAUTION·DANGER 가 안전선 기준이다. 없으면 0원 미만(GAP)만
-- 판정할 수 있어 P0-08 자금 부족 알림이 반쪽이 된다(아키텍처 §11).
-- API 22장에 SAFETY_LINE_NOT_SET(422)이 이미 정의돼 있는 것도 같은 전제다.
--
-- ⚠ V1 헤더는 이 테이블을 "ERD §1.6 P1 확장. P0-08 착수 시 판단한다"로 뺐다.
--   아키텍처 §11 의 P0 승격과 반대였고, 이 마이그레이션이 §11 쪽을 채택한다.
--
--   V1 헤더의 그 줄은 고치지 않는다 — V1 은 서버에 적용돼 동결이고 체크섬이 주석까지
--   포함하므로, 한 글자만 바꿔도 앱이 부팅에 실패한다. 그 줄은 "V1 시점의 판단"으로
--   읽고, 현재 판정은 이 파일이다. 두 문서가 어긋나 보이는 이유가 여기 있다.
--
-- forecast 가 아니라 core 에 두는 이유는 ALERT 와 같다 — forecast 가 읽어서 위험 등급을
-- 판정하지만 설정 자체는 사업장 속성이고 쓰기 주체가 core 다. 모듈 의존이
-- forecast → core 단방향이므로 core 가 소유해야 역방향 참조가 생기지 않는다.
CREATE TABLE core.safety_balance_policy (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT        NOT NULL,
    method            VARCHAR(30)   NOT NULL DEFAULT 'MANUAL',
    amount            NUMERIC(19,4) NOT NULL,
    -- 매월 고정비 집계로 자동 갱신할지. P0 범위는 수동 설정만이라 기본 false 다.
    auto_update       BOOLEAN       NOT NULL DEFAULT false,
    -- 추천값 산출 근거(API 12.1 recommendations, P1). 수동 설정이면 null.
    calculation_basis JSONB,
    -- created_at 은 ERD 표에 없지만 둔다. 변경되는 업무 테이블이라 엔티티가
    -- BaseEntity 를 상속하고, BaseEntity 가 두 컬럼을 모두 요구한다.
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_sbp_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    -- 사업장당 1행. 이 UNIQUE 가 곧 "하나만 유지"의 강제 수단이다(ERD §1.6).
    -- 조회도 business_id 단건이라 별도 인덱스가 필요 없다.
    CONSTRAINT uk_sbp_business UNIQUE (business_id),
    CONSTRAINT ck_sbp_method   CHECK (method IN ('MANUAL', 'FIXED_COST_BASED', 'ESSENTIAL_EXPENSE_BASED')),
    -- 음수 안전선은 의미가 없다. "설정 안 함"은 행이 없는 것으로 표현한다
    -- (API 12.1 — 설정 전에는 amount: null 이고 위험 등급은 0원 기준만 판정한다).
    CONSTRAINT ck_sbp_amount   CHECK (amount >= 0)
);
