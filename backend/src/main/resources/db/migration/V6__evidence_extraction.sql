--
-- AI 2번(OCR·VLM)이 KORIE test 359장 실측까지 끝내 놓고 결과를 넣을 곳이 없었다.
-- 현재는 AiResultApplier 가 JOB.result JSONB 에 통째로 넣고 Job 만 완료 처리한다.
--
-- 합의 문서가 "지금이 결정 비용이 0인 시점"이라고 한 이유가 이것이다 — 세 테이블이
-- 아직 없어서 ALTER 없이 CREATE 한 번으로 끝난다. 특히 ⑤의 세 건은 테이블이 생긴
-- 뒤에 고치면 ALTER 가 세 번이고, 그 사이 stub 연동이 INSERT 에서 깨진 채로 있게 된다.
--
-- ⚠ ITEM 이 먼저다. EVIDENCE_ITEM.item_id 가 참조한다.
