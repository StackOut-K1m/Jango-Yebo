-- =============================================================================
-- 1. ITEM — 품목 마스터 (ERD §ITEM)
-- =============================================================================

-- 증빙 품목 가계부가 참조하는 사업장별 공통 품목 마스터. 지금 만드는 이유는 하나,
-- EVIDENCE_ITEM.item_id 의 FK 대상이라서다. 품목 API(13.4~) 는 아직 없다.
CREATE TABLE core.item (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL,
    name        VARCHAR(255) NOT NULL,
    -- 표기 흔들림 별칭. 품목 정규화(20.5) 1차 규칙이 여기를 본다.
    aliases     JSONB,
    category    VARCHAR(50),
    base_unit   VARCHAR(20),
    -- 병합된 품목은 지우지 않고 비활성화한다 — 과거 증빙이 참조하고 있다.
    active      BOOLEAN      NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT uk_item_name     UNIQUE (business_id, name, base_unit)
);

CREATE INDEX ix_item_business ON core.item (business_id) WHERE active = true;


-- =============================================================================
-- 2. EVIDENCE_EXTRACTION — 추출 1회분 (합의 ①·⑤·⑦)
-- =============================================================================

CREATE TABLE core.evidence_extraction (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id    BIGINT       NOT NULL,
    model_name     VARCHAR(100) NOT NULL,

    -- ⑤ 워커는 항상 null 을 보낸다. Anthropic 응답의 model 이 이미 고정 식별자
    --    (claude-sonnet-5)라 별도 버전이 없다. ERD 의 NN 을 따르면 INSERT 가 전부 깨진다.
    model_version  VARCHAR(100),

    -- ⑤ 재현성의 실제 키. "언제부터 정확도가 떨어졌나"에 답하는 값은 model_version 이
    --    아니라 이것이다 — 프롬프트를 v1→v2 로 바꿨을 때 상호명 정확도가 80.8% → 97.9% 로
    --    움직였다(ai/experiments/README.md).
    prompt_version VARCHAR(100),

    pipeline       VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,

    -- ① 워커 data 를 그대로 넣는다. taxableAmount·taxFreeAmount·discountAmount·validation
    --    까지 통째로. 헤더 확장 필드가 계속 늘어나는데 그때마다 컬럼을 파면 마이그레이션이
    --    계약 개정마다 따라붙는다. 13.2 응답에는 discountAmount·validation 만 꺼내 노출한다.
    header_data    JSONB,

    confidence     NUMERIC(4,3),
    is_current     BOOLEAN      NOT NULL DEFAULT true,

    -- ⑦ 정확도의 분모. 사용자가 고친 게 없어도 채운다 — 안 채우면 "고친 적 없는 추출"과
    --    "아직 안 본 추출"이 구분되지 않아 정확도가 실제보다 높게 나온다.
    confirmed_at   TIMESTAMPTZ,
    confirmed_by   BIGINT,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_extraction_evidence FOREIGN KEY (evidence_id) REFERENCES core.evidence (id),
    CONSTRAINT fk_extraction_user     FOREIGN KEY (confirmed_by) REFERENCES core.users (id),
    -- ⑤ STUB 은 연동 검증용(계약 20.2 v1.9). 빠뜨리면 stub 모드 INSERT 가 깨지는데,
    --    그건 백엔드·워커를 API 키 없이 잇는 유일한 경로다.
    CONSTRAINT ck_extraction_pipeline CHECK (pipeline IN ('OCR_PIPELINE', 'VLM', 'STUB')),
    -- PARTIAL 을 FAILED 로 접지 않는다(20.2) — 쓸 수 있는 결과를 버리게 된다.
    CONSTRAINT ck_extraction_status   CHECK (status IN ('COMPLETED', 'PARTIAL'))
);

-- ERD 규정: 증빙당 현재 결과는 하나. 재추출하면 이전 행의 is_current 를 내린다.
CREATE UNIQUE INDEX uk_extraction_current ON core.evidence_extraction (evidence_id)
    WHERE is_current = true;


-- =============================================================================
-- 3. EVIDENCE_ITEM — 추출된 품목 행 (합의 ②·④)
-- =============================================================================

CREATE TABLE core.evidence_item (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_id      BIGINT       NOT NULL,
    -- 정규화가 붙기 전이거나 못 붙였으면 null.
    item_id            BIGINT,
    raw_name           VARCHAR(255) NOT NULL,
    quantity           NUMERIC(14,3),
    unit               VARCHAR(20),
    unit_price         NUMERIC(14,2),

    -- ② 인쇄된 행 금액(할인 전). 13.2·13.3 이 쓰는 필드라 없으면 화면이 못 그린다.
    amount             NUMERIC(14,2),

    -- ② 행 에누리를 <b>양수</b>로 받는다. 순액 = amount - COALESCE(discount_amount, 0).
    --    음수 품목 행을 만들지 않기로 한 합의(②)의 저장 쪽이다 — 음수 행을 허용하면
    --    수량×단가와 금액의 관계가 행마다 달라져 검산이 성립하지 않는다.
    discount_amount    NUMERIC(14,2),

    -- ② 세금계산서·거래명세서용. 소매 영수증에는 행별 공급가·부가세가 인쇄되지 않아 null.
    supply_amount      NUMERIC(14,2),
    vat_amount         NUMERIC(14,2),

    -- ④ RULE / SIMILARITY / LLM. 미매칭은 null. §6.5 "규칙이 90% 이상을 처리한다"는
    --    발표 수치가 이 컬럼의 집계다 — 안 남기면 그 문장을 근거 없이 말하게 된다.
    matched_by         VARCHAR(12),

    -- ⑥ boundingBox. VLM 경로는 좌표를 신뢰성 있게 못 내서 항상 null 이고 STUB 만 채운다.
    --    컬럼은 남긴다 — OCR_PIPELINE 공급자를 붙이면 실제 값이 들어온다.
    source_coordinates JSONB,

    CONSTRAINT fk_evidence_item_extraction FOREIGN KEY (extraction_id)
        REFERENCES core.evidence_extraction (id) ON DELETE CASCADE,
    CONSTRAINT fk_evidence_item_item FOREIGN KEY (item_id) REFERENCES core.item (id),
    CONSTRAINT ck_evidence_item_matched_by
        CHECK (matched_by IS NULL OR matched_by IN ('RULE', 'SIMILARITY', 'LLM')),
    CONSTRAINT ck_evidence_item_discount CHECK (discount_amount IS NULL OR discount_amount >= 0)
);

CREATE INDEX ix_evidence_item_extraction ON core.evidence_item (extraction_id);


-- =============================================================================
-- 4. EVIDENCE_CORRECTION — 사용자 수정 이력 (합의 ⑦)
-- =============================================================================

-- 실사용 정확도를 얻는 유일한 방법이다. 실험 세트 정확도(KORIE 359장)는 우리가 고른
-- 이미지에 대한 값이고, 사장님이 실제로 무엇을 고쳤는지는 여기서만 나온다.
--
-- 지금 넣는 이유는 EVIDENCE_EXTRACTION 과 같다 — 나중에 넣으면 그 전에 확정된 추출들의
-- 수정 이력이 영영 비어 있게 되고, 분모(confirmed_at)만 있고 분자가 없는 구간이 생긴다.
CREATE TABLE core.evidence_correction (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_id BIGINT       NOT NULL,
    -- 계약 필드 키. 품목은 `items[3].amount` 처럼 인덱스를 포함한다.
    field         VARCHAR(100) NOT NULL,
    -- null 이면 모델이 못 읽은 것, 아래가 null 이면 사용자가 지운 것이다.
    before_value  TEXT,
    after_value   TEXT,
    corrected_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_correction_extraction FOREIGN KEY (extraction_id)
        REFERENCES core.evidence_extraction (id) ON DELETE CASCADE,
    -- 안 바뀐 것을 넣으면 분자가 부풀어 정확도가 실제보다 낮게 나온다.
    CONSTRAINT ck_correction_changed CHECK (before_value IS DISTINCT FROM after_value)
);

CREATE INDEX ix_correction_extraction ON core.evidence_correction (extraction_id);
