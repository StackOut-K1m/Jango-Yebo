-- 예측 옵션 (API 10.7) — S15P21C105-137
--
-- 10.7 이 여섯 필드를 저장하라고 하는데 저장할 자리가 없었다. BUSINESS 에 컬럼이 없고
-- 전용 테이블도 없었으며, FORECAST_RUN.applied_options 는 10.7 자신이 "실행 당시 값을
-- 그대로 유지한다"고 못박은 스냅샷이라 원본이 될 수 없다. ERD v1.11 이 이 표를 정의했다.
--
-- forecast 스키마에 두는 이유: forecast 모듈이 그 스키마를 소유한다(package-info).
-- core.business 에 컬럼을 더하면 forecast 가 core 스키마를 쓰는 셈이라 소유권이 흐려진다.
--
-- 행이 없는 것이 정상이다 — 사용자가 옵션을 한 번도 건드리지 않은 상태이고,
-- 조회는 404 가 아니라 기본값을 돌려준다. SAFETY_BALANCE_POLICY 와 같은 모양이다.

CREATE TABLE forecast.forecast_setting (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT      NOT NULL,
    -- P1-07. 계절성 기능이 서기 전까지 저장만 되고 곡선에 반영되지 않는다.
    apply_seasonality    BOOLEAN     NOT NULL DEFAULT FALSE,
    -- P1-06.
    apply_material_index BOOLEAN     NOT NULL DEFAULT FALSE,
    -- P1-11.
    apply_vat_reserve    BOOLEAN     NOT NULL DEFAULT FALSE,
    -- P0-07. **P0 에서 곡선을 실제로 바꾸는 유일한 토글이다.**
    -- 끈 상태에서도 곡선과 부족일은 정상 산출된다(인수 조건).
    apply_residual_model BOOLEAN     NOT NULL DEFAULT TRUE,
    -- 사용자가 수동 입력하는 성수기·비수기 월 배열 [7, 8, 12].
    -- 검색 대상이 아니라 JSONB 다(ERD 11장). P1-07 전까지 저장만 하고 읽지 않는다.
    peak_months          JSONB,
    off_months           JSONB,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_fs_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT uk_fs_business UNIQUE (business_id)
);
