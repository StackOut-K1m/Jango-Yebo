-- 공고 요약을 따로 담는다 (17.2 rawSummary)
--
-- 17.2 가 상세 화면에 `rawSummary`(공고 원문 요약)를 요구하는데 **채울 데가 없었다.**
-- 20.6 워커 출력 목록에도 없어서 영영 비는 자리였다(99_구현현황 §3.33).
--
-- **수집기가 준다.** 기업마당 목록 API 가 `bsnsSumryCn`(사업개요내용)을 그대로 실어 준다 —
-- 2026-09-15 공식 응답 예시로 확인했다. 모델에게 요약을 시킬 일이 아니라 받아 적으면 되는
-- 값이라, 워커 계약을 여는 대신 여기로 온다.
--
-- raw_text 와 다르다: raw_text 는 LLM 이 읽을 **원문 전문**(상세 페이지 본문)이고,
-- raw_summary 는 사람이 읽을 **한두 문장**이다. 원문이 없어 구조화를 못 건 공고도
-- 요약은 있을 수 있으므로 서로를 대신하지 않는다.
-- =============================================================================

