-- =============================================================================
-- 워커가 받지 못한 작업의 재시도 시각 (AI 담당 요청 2026-09-14)
--
-- **접수 실패와 무응답은 위험이 다른데 대기가 같았다.**
--
--   연결 거부(202 못 받음)  워커에 일이 떠 있지 않다 → 재시도해도 중복 과금 0
--   접수됨 · 콜백 없음       워커가 이미 분류했을 수 있다 → 10분 기다려야 안전
--
-- 지금까지 둘 다 PROCESSING 으로 남아 스위퍼의 stall-timeout(10분)을 기다렸다. 실측으로
-- **분류가 20분 동안 멈췄다** — 워커가 꺼진 사이 Job 이 갇혔고, 8.5 버튼을 눌러도
-- enqueueOrCurrent 가 그 Job 을 돌려줘 새 작업이 생기지 않았다. 스위퍼가 회수한 직후
-- 워커가 3초 늦게 떠서 재시도마저 실패하고 FAILED 로 끝났다.
--
-- **접수도 안 된 작업은 대기열로 되돌린다.** 워커가 손댄 적이 없으니 그게 안전하고,
-- 살아나면 다음 폴링(기본 2초)에 바로 집어간다.
--
-- 되돌리자마자 다시 집으면 워커가 죽어 있는 동안 초당 재시도가 된다. 이 컬럼이 그것을
-- 막는다 — 이 시각 전에는 claim 대상에서 빠진다.
--
-- 인덱스는 두지 않는다. 대기열은 사업장 수만큼도 안 쌓이고, claim 은 이미
-- status·job_type 으로 좁힌 뒤 이 컬럼을 본다.
-- =============================================================================

ALTER TABLE core.job
    ADD COLUMN next_attempt_at TIMESTAMPTZ;

COMMENT ON COLUMN core.job.next_attempt_at IS
    '이 시각 전에는 워커가 집지 않는다. 워커가 받지 못한(202 미수신) 작업을 되돌릴 때만 채운다';
