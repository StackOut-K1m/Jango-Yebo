-- =============================================================================
-- 서류 발급처 사전 (P1-15 · API 17.4 · ERD `DOCUMENT_GUIDE`)
--
-- 번호 주의 — 착수 시점(2026-09-16) develop 최상단은 V29(재료비 What-if 제외)였고
-- 원격 피쳐 브랜치를 전부 훑어 V30 이 비어 있는 것을 확인했다.
--
-- **사업장 공용 기준 데이터다.** business_id 가 없다 — 사업자등록증명을 어디서 떼는지는
-- 사장님마다 다르지 않다. 그래서 BusinessScoped 도 구현하지 않는다.
--
-- ## 이 표가 17.2 의 빠진 반쪽이다
--
-- 20.6 워커는 `requiredDocuments[]` 에 **이름·발급처·발급방법까지만** 담고 `issueUrl`·`fee`
-- 는 일부러 비워 보낸다(`ai/app/nlp/schemas.py` RequiredDocument). 공고 본문에서 주워 온
-- URL 을 그대로 실으면 죽은 링크나 엉뚱한 기관 페이지가 사장님에게 나가기 때문이다.
-- 17.2 명세는 그 두 칸이 채워진 응답을 요구한다 — **채우는 자리가 여기다.**
-- =============================================================================

CREATE TABLE core.document_guide (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_name  VARCHAR(200)  NOT NULL,
    issuer         VARCHAR(200)  NOT NULL,

    -- ⚠ **ERD 이탈 — NN 을 풀었다.** ERD 는 `issue_url NN` 이지만 통장 사본·임대차계약서처럼
    -- **발급받는 게 아니라 이미 갖고 있는 서류**가 제출 목록에 늘 들어간다. 이것들을 사전에서
    -- 빼면 17.2 가 이름만 덩그러니 보여 주고, 사장님은 있지도 않은 발급처를 찾아다닌다.
    -- 링크 없이 `method = '직접 준비'` 로 담는 편이 「발급처가 없다」를 말해 준다.
    issue_url      VARCHAR(1000),

    method         VARCHAR(200)  NOT NULL,
    fee            NUMERIC(19,4) NOT NULL DEFAULT 0,
    estimated_time VARCHAR(100),
    notes          VARCHAR(500),

    -- ⚠ **ERD 에 없는 컬럼이다.** 워커가 주는 서류명은 자유 문장이라 표기가 흔들린다 —
    -- 「사업자등록증명」·「사업자등록증명원」·「사업자등록증 사본」이 다 같은 서류다.
    -- 이름이 한 글자만 달라도 못 붙이면 **링크가 조용히 사라진다**(빈 응답이 아니라
    -- 링크만 빠진 응답이라 화면에서 티가 안 난다). 그래서 별칭을 데이터로 둔다.
    -- 정규화 규칙은 DocumentGuideService.normalize 한 곳에만 있다.
    match_keys     TEXT[]        NOT NULL DEFAULT '{}',

    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uk_dg_name UNIQUE (document_name),
    CONSTRAINT ck_dg_fee CHECK (fee >= 0)
);

-- 별칭 조회가 이 표의 주 경로다(17.2 가 서류 이름으로 사전을 찾는다).
CREATE INDEX ix_dg_match_keys ON core.document_guide USING GIN (match_keys);

COMMENT ON TABLE core.document_guide IS '서류 발급처 사전 (API 17.4). 전역 기준 데이터';
COMMENT ON COLUMN core.document_guide.match_keys IS '정규화된 서류명 별칭. 공백·중점·괄호를 뺀 소문자';

