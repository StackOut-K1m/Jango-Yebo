-- 출처가 공고를 마지막으로 고친 시각 (P1-15)
--
-- **이게 없으면 매일 1,526건의 상세 페이지를 전부 받아야 한다.** 원문이 바뀌었는지
-- 알 방법이 그것뿐이기 때문이다 — 0.7초 간격이면 18분이고, 기업마당에 하루 1,526번
-- 요청하는 일이다.
--
-- 기업마당 목록 API 가 `updtPnttm` 을 준다(공식 문서에는 없고 실호출로 확인, 2026-09-15).
-- 이 값이 그대로면 상세를 받을 필요가 없다.
--
-- collected_at 과 다르다: collected_at 은 **우리가 받아 온 시각**이라 매번 바뀌고,
-- source_updated_at 은 **출처가 고친 시각**이라 안 바뀌는 것이 정상이다. 변경 감지에
-- 쓸 수 있는 것은 뒤쪽뿐이다.
--
-- ⚠ 이것만 믿지는 않는다. 출처가 내용을 고치면서 이 값을 안 올릴 수도 있으므로,
-- 원문이 실제로 달라졌는지도 함께 본다(SupportProgramIngestService).
-- =============================================================================

ALTER TABLE core.support_program ADD COLUMN source_updated_at TIMESTAMPTZ;

COMMENT ON COLUMN core.support_program.source_updated_at IS
    '출처가 공고를 마지막으로 고친 시각(기업마당 updtPnttm). 이게 그대로면 상세 페이지를 다시 받지 않는다';

-- 구조화가 안 끝난 공고를 고르는 경로. 수집 배치가 매번 훑는다.
-- ix_sp_unstructured(collected_at) 가 이미 있어 여기서는 인덱스를 더하지 않는다.
