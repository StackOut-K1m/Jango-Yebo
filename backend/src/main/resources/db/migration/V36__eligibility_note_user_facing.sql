-- =============================================================================
-- eligibility_note 를 사용자 문장으로 (API 14.3 · S15P21C105-260)
--
-- **이 문구는 사장님이 그대로 읽는다.** 화면이 서식 목록에서 설명으로 붙인다
-- (frontend TaxDraftScreen). 그런데 V27 이 넣은 값은 개발자에게 하는 말이었다 —
--
--   '복식부기의무자 — 필요 서류 체크리스트와 준비자료 패키지(14.2)만 안내한다'
--
-- 「(14.2)」는 우리 명세 절 번호이고 「~만 안내한다」는 구현 범위를 설명하는 말이라,
-- 사장님에게는 둘 다 읽을 이유가 없는 글자다. 프론트에서 회신이 왔다(2026-09-18).
--
-- **금액 기준은 새로 넣지 않는다.** 업종별 간편장부 기준(소매 3억, 서비스 7,500만 등)이
-- 팀 문서에 정리돼 있지만 그 문서 스스로 「화면 문구에 넣기 전에 국세청 안내로 확인한다」고
-- 적어 뒀다. 확인되지 않은 세법 수치를 화면에 내보내지 않는다(도메인 규칙 4 — 세무 값을
-- 자동 확정하지 않는다). SIMPLE_LEDGER 의 음식점업 기준은 V27 이 이미 넣어 둔 값이라
-- 그대로 옮긴다.
--
-- ⚠ 남은 것 — 음식점업 외 업종 기준이 없다. 확인된 문구를 받으면 다음 마이그레이션에서
-- 채운다.
-- =============================================================================

UPDATE core.tax_form_template
   SET eligibility_note =
       '거래를 간단한 장부로 적는 사업자가 쓰는 서식입니다. '
       '음식점업은 직전 연도 수입금액이 1억 5천만원 미만이거나 올해 새로 연 경우가 해당합니다. '
       '내 유형은 홈택스 신고도움서비스에서 확인할 수 있습니다.'
 WHERE form_type = 'SIMPLE_LEDGER' AND tax_year = 2026;

UPDATE core.tax_form_template
   SET eligibility_note =
       '장부를 쓰지 않았을 때 정해진 경비율로 소득을 계산하는 방식입니다. '
       '계좌 거래가 정리되어 있다면 간편장부 쪽을 먼저 살펴보시는 것이 좋습니다.'
 WHERE form_type = 'STANDARD_RATE' AND tax_year = 2026;

UPDATE core.tax_form_template
   SET eligibility_note =
       '국세청이 신고서를 미리 채워 주는 유형입니다. '
       '홈택스에서 안내받은 금액을 우리 정산 기록과 맞춰 보실 수 있습니다.'
 WHERE form_type = 'SIMPLE_RATE' AND tax_year = 2026;

UPDATE core.tax_form_template
   SET eligibility_note =
       '복식부기로 장부를 써야 하는 사업자입니다. '
       '재무제표와 조정계산서는 이 서비스에서 만들지 않습니다 — '
       '필요한 서류 목록과 세무대리인에게 전달할 자료를 준비해 드립니다.'
 WHERE form_type = 'DOUBLE_ENTRY' AND tax_year = 2026;

COMMENT ON COLUMN core.tax_form_template.eligibility_note IS
    '서식 목록에서 사장님이 그대로 읽는 설명 (API 14.3 eligibilityNote). '
    '명세 절 번호·구현 범위 설명을 넣지 않는다. 확인되지 않은 세법 수치도 넣지 않는다.';
