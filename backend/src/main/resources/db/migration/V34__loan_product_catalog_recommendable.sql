-- 카탈로그 대출 상품 12건을 추천에 노출한다 (API 16.3 · P1-14)
--
-- LOAN_SYNC 는 recommendable 을 갱신 대상에서 뺀다(LoanProductSyncService). 그래서 금융망
-- 상품을 아무리 동기화해도 전부 꺼진 채로 들어오고, 추천 조회(LoanProductsService 의
-- `WHERE recommendable`)는 빈 목록을 돌려준다. 지금까지 이것을 켜는 유일한 경로는
-- scripts/seed-loan-visibility.mjs 가 찍어 주는 SQL 을 사람이 psql 에 붙여 넣는 것이었다.
--
-- 그 수동 단계가 빠지면 **오류 없이 조용히 빈다.** 화면에는 「보여 드릴 대출 상품이 아직
-- 없습니다」만 뜨고 로그에도 아무것도 안 남는다. 시연 서버에서 이 문구를 보고 원인을 찾는
-- 일이 없도록, 우리가 등록한 카탈로그(scripts/seed/loan-products.json)만큼은 부팅 시점에
-- 켜진 상태로 고정한다.
--
-- -----------------------------------------------------------------------------
-- **기본값은 그대로 FALSE 다.** 뒤집지 않는다.
--
-- 금융망에는 대출 상품 삭제 API 가 없고(LOAN_01~10 어디에도 없다) 팀 apiKey 를 가진 누구나
-- LOAN_02 로 상품을 만들 수 있다 — 등록 폼이 우리 저장소 안(tools/fin-console)에 있다.
-- 기본을 TRUE 로 두면 실수가 곧바로 사장님 화면에 「이 대출을 받으세요」로 나가고, 지울
-- 방법이 없어 사후에 끄는 수밖에 없다.
--
-- 가정이 아니다. 지금 목록에 「한국은행 대출 상품 · E · 연 10% · 7일」이 한 건 있다 —
-- 우리가 시드하기 전부터 팀 앱에 있던 그 하나다(scripts/seed/loans.mjs 머리말). 아래
-- 목록에 없으므로 이 마이그레이션이 지나가도 꺼진 채로 남는다. 그것이 요점이다.
--
-- -----------------------------------------------------------------------------
-- **UPDATE 가 아니라 INSERT 인 이유** — 마이그레이션은 앱 부팅 때 돈다. 그 시점에
-- loan_product 는 비어 있다(채우는 것은 LOAN_SYNC 이고 수동 호출뿐이다). UPDATE 만 두면
-- 새 DB 에서 0 행을 고치고 끝난다.
--
-- **DO NOTHING 이 아니라 DO UPDATE 인 이유** — 이미 동기화를 돌린 DB 에는 행이 FALSE 로
-- 들어와 있다. DO NOTHING 이면 그런 DB 에서는 아무 일도 일어나지 않아 목적을 못 이룬다.
-- 켜기만 하고 끄지는 않는다(WHERE NOT loan_product.recommendable) — 사람이 판단해 켜 둔
-- 것을 되돌리지 않는 seed-loan-visibility.mjs 의 규칙 그대로다.
--
-- **갱신하는 것이 recommendable 뿐인 이유** — 행이 이미 있으면 그쪽이 금융망에서 온 값이라
-- 여기 박아 둔 것보다 최신이다. 금액·금리·기간을 덮어쓰지 않는다.
--
-- -----------------------------------------------------------------------------
-- external_id(accountTypeUniqueNo)를 박아 두는 근거 — 금융망에 삭제 API 가 없어 한 번 발급된
-- 고유번호가 사라지지 않는다. 아래 값은 2026-09-17 LOAN_03(inquireLoanProductList) 응답에서
-- 그대로 옮긴 것이고, 같은 호출로 13건 전부가 ck_lp_grade·ck_lp_period·ck_lp_balance 를
-- 만족함을 확인했다.
--
-- collected_at 은 컬럼 기본값 now() 가 붙는다. 실제 수집 시각이 아니라 이 마이그레이션이
-- 도는 시각이고, 첫 LOAN_SYNC 가 바로잡는다. 없는 값을 지어내지 않으려면 NULL 이 맞지만
-- NOT NULL 컬럼이라 그럴 수 없다 — 스키마를 흔드는 것보다 이 주석이 낫다.
-- =============================================================================

