-- 잔액 맞추기 흔적을 예측 입력에서 뺀다 (일회성 보수)
--
-- 금융망 샌드박스는 잔액을 직접 정할 수 없어 **입금 거래로 만든다.** 시드가 계좌 개설에
-- 「개발용 초기 잔액」(scripts/fin-account.mjs)을, 기준일 잔액 맞추기에 「전기이월」
-- (scripts/seed/pipeline.mjs — alignBalance)을 넣는다. 사장님이 한 거래가 아닌데
-- 동기화되면 매출처럼 보인다.
--
-- 파이프라인에 지우는 절차가 이미 있다(excludeBalanceArtifacts). 그런데 CLI(scripts/seed.mjs)만
-- 그걸 부르고 웹 콘솔(tools/seed-console)은 부르지 않아, 콘솔로 시드한 사업장에 흔적이 그대로
-- 남았다. 실측(2026-09-15 배포): IS_EXCLUDED 인 거래가 DB 전체에 0건이고, 사업장 4 의
-- 「전기이월」 940,899원 한 건이 예측 입력과 반복 패턴에 정상 입금으로 들어가 있었다.
--
-- 콘솔은 같은 커밋에서 고친다. 이 마이그레이션은 이미 쌓인 행을 되돌리는 쪽이다.
--
-- **적요로 거르는 규칙을 제품에 심는 것이 아니다.** 운영 코드가 적요 문자열을 보게 하면
-- 개발 도구의 흔적이 제품의 규칙으로 굳는다(pipeline.mjs 주석). 여기서만, 이미 들어온
-- 행에 대해, 한 번 한다 — 앞으로 생기는 것은 시드 쪽이 막는다.
--
-- 지우지 않고 표시만 한다. 그 거래는 「금융망에서 실시간으로 가져왔다」는 증거이기도 해서
-- 원장에는 남겨야 한다(alignBalance 주석). 제외는 예측 입력에서만 빼는 것이라 부딪히지 않는다.
--
-- source_type 을 함께 본다. 적요만 보면 사장님이 직접 「전기이월」이라 적어 올린 CSV 행까지
-- 집어간다. 흔적은 반드시 금융망에서 들어오므로 FIN_API 다.
--
-- 새 DB 에서는 0건을 고치고 끝난다.
-- =============================================================================

UPDATE core.transaction
   SET is_excluded = TRUE,
       updated_at  = now()
 WHERE source_type = 'FIN_API'
   AND is_excluded = FALSE
   AND description IN ('전기이월', '전기이월 정산', '개발용 초기 잔액');
