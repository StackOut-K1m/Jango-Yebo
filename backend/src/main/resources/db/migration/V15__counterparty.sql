-- =============================================================================
-- 거래처 사전 (ERD 1.5 COUNTERPARTY · API 8.6 · P1-01 2단계)
--
-- 도메인 규칙 3 — "확정된 거래처↔분류 매핑은 DB에 캐시해서 재사용한다. LLM 호출은 처음 보는
-- 패턴에만." 지금은 미분류면 무조건 LLM 을 타므로, 지난달 사장님이 확정한 것과 같은 적요의
-- 이번 달 거래도 값을 다시 치른다. 명세 8.5 도 "규칙 → 거래처 사전 순으로 먼저 처리하고
-- 남은 거래만 배치로" 라고 적고 있다.
--
-- 이 마이그레이션은 사전을 「쌓는」 자리까지다. 분류 전에 사전을 「보는」 것은 다음 단계다 —
-- 채우지 않은 사전으로 거르면 아무것도 안 걸러지므로 순서가 이쪽이 먼저다.
--
-- ERD 와 다른 점 두 개를 적어 둔다. confirmed_count·last_used_at 은 ERD 1.5 표에 없지만
-- API 8.6 응답이 요구한다. 매번 이력에서 세면 목록 한 줄마다 집계가 붙으므로 확정할 때
-- 올린다. avg_delay_days 는 만들지 않는다 — ERD 가 PLANNED_TRANSACTION 매칭 결과에서
-- 집계한다고 정했고 그 경로(P1-05)가 아직 없다.
-- =============================================================================

CREATE TABLE core.counterparty (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         BIGINT       NOT NULL,
    -- 표준 거래처명(API displayName). 지금은 거래 적요를 그대로 쓴다 — 사람이 확인한
    -- 거래처명이 아직 없기 때문이다(LLM 추정값은 원천으로 쓰지 않는다).
    canonical_name      VARCHAR(255) NOT NULL,
    -- 적요 별칭(API matchPatterns). 표기가 갈리는 거래처를 한 줄로 모으는 자리이고,
    -- 지금은 채우지 않는다.
    aliases             JSONB,
    default_category_id BIGINT,
    -- 열쇠의 일부라 필수다. 축적 경로가 거래의 flow_type(NOT NULL)에서 가져오므로 빌 일이 없다.
    -- ERD 1.5 는 Optional 로 적어 뒀는데, 유일 인덱스에 들어가는 컬럼이 nullable 이면
    -- Postgres 에서 NULL 끼리는 중복으로 보지 않아 같은 적요가 여러 줄로 갈린다.
    default_flow_type   VARCHAR(20)  NOT NULL,
    -- 몇 번 확정됐는가(API confirmedCount). 사전을 믿을지 가르는 근거가 된다.
    confirmed_count     INT          NOT NULL DEFAULT 0,
    last_used_at        TIMESTAMPTZ,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_cp_business FOREIGN KEY (business_id)         REFERENCES core.business (id),
    CONSTRAINT fk_cp_category FOREIGN KEY (default_category_id) REFERENCES core.transaction_category (id),
    CONSTRAINT ck_cp_flow     CHECK (default_flow_type IS NULL
                                     OR default_flow_type IN ('DEPOSIT', 'WITHDRAWAL'))
);

-- 조회도 이 순서로 들어오고(사업장 안에서 적요와 방향으로 찾는다) 중복 축적도 이것이 막는다.
--
-- **방향이 열쇠에 들어가는 이유.** 은행 적요에는 브랜드명이 아니라 법인명이 찍혀서,
-- 같은 문자열이 입금과 출금 양쪽에 온다. 배달의민족은 정산금을 입금하고 광고비를 출금하는데
-- 둘 다 적요가 `우아한형제들` 이다(AI 평가셋 `ai/evals/rewrite.py` 의 「함정 3」이 이것을
-- 일부러 만들어 둔다). 신한카드도 매출 정산금이 들어오고 카드 대금이 나간다.
--
-- 적요만 열쇠로 쓰면 그 거래처가 한 줄이 되어 마지막 확정이 이기고, **출금 거래에 입금
-- 카테고리가 붙는다** — 카테고리는 방향이 고정돼 있다(입금 7종·출금 16종). 워커는 이 오류를
-- CATEGORY_DIRECTION 표로 막지만 사전 경로에는 그런 검사가 없었다. 게다가 그렇게 붙은 분류는
-- needs_confirmation = false 라 사장님에게 묻지도 않는다.
CREATE UNIQUE INDEX uk_cp_business_name_flow
    ON core.counterparty (business_id, canonical_name, default_flow_type);

-- 8.6 목록은 최근 쓴 순이다.
CREATE INDEX ix_cp_recent ON core.counterparty (business_id, last_used_at DESC);

COMMENT ON TABLE core.counterparty IS
    '사업장별 정규 거래처 사전 — 확정된 적요↔분류 매핑 캐시 (도메인 규칙 3)';
COMMENT ON COLUMN core.counterparty.canonical_name IS
    '지금은 거래 적요 원문. 사람이 확인한 거래처명이 쌓이면 그쪽으로 옮기고 적요는 aliases 로 내린다';
COMMENT ON COLUMN core.counterparty.default_flow_type IS
    '열쇠의 일부. 같은 적요가 입금·출금 양쪽에 오므로(우아한형제들 = 정산금 입금 + 광고비 출금) 방향별로 따로 기억한다';
