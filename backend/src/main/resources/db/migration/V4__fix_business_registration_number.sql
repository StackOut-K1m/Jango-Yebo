-- =============================================================================
-- BUSINESS.registration_number — 암호문이 들어가지 않던 것을 고친다
--
-- V1 은 이 컬럼을 VARCHAR(64) 로 잡았다. 평문("123-45-67890" 12자) 기준의 크기이며
-- 암호문 기준이 아니었다. FieldEncryptor 의 출력 길이는 결정적이다:
--
--   바이트 = IV 16 + 평문 + GCM 태그 16,  hex 인코딩이라 문자 수는 그 2배
--   "123-45-67890"(12바이트) -> 44바이트 -> 88자    >  64  ->  INSERT 거부 -> 500
--
-- 평문 0자여야 딱 64자다. 즉 이 컬럼에는 어떤 값도 들어간 적이 없다.
-- 프론트가 사업장 등록 화면(S15P21C105-52)을 만들며 처음 밟았다.
--
-- ⚠ 리팩터링(9465020, Encryptors.delux -> JDK 직접 조립)과 무관하다.
--   두 구현의 암호문 형식이 동일함을 FieldEncryptorCompatibilityTests 가 증명한다.
--   V1 부터 깨져 있었고, 사업자등록번호를 실제로 보낸 적이 없어 드러나지 않았다.
--
-- 512 는 같은 성격의 두 컬럼(ACCOUNT.account_number_encrypted, USER.fin_user_key)과
-- 맞춘 값이다. 암호화 컬럼 3개 중 이것만 다른 기준으로 잡혀 있었다.
--
-- V1 상단 마이그레이션 규칙 대조 — "타입 변경 금지"는 좁히는 방향을 막는 규칙이다.
-- VARCHAR 를 넓히면 구버전 코드가 쓰던 값은 그대로 들어가므로 롤백이 깨지지 않는다.
-- 여기서는 구버전이 쓸 수 있던 값 자체가 없었으므로 더더욱 무해하다.
-- =============================================================================

ALTER TABLE core.business
    ALTER COLUMN registration_number TYPE VARCHAR(512);


-- 마스킹 값을 쓰기 시점에 계산해 저장한다.
--
-- 응답의 businessRegNoMasked 를 만들 때 암호문에 substring 을 걸고 있었다(복호화 없음).
-- 컬럼만 넓히면 500 은 사라지지만 "***-**-a3f9c" 같은 암호문 조각이 나간다.
--
-- 읽을 때 복호화하는 대신 저장하는 이유:
--   - 임의 IV 라 암호문으로는 검색·비교가 불가능하다
--   - 목록 조회마다 복호화하면 표시 목적으로 키를 계속 만지게 된다
--   - ACCOUNT.account_number_masked 가 이미 같은 방식이다. 같은 문제를 두 방식으로
--     풀면 다음 사람이 어느 쪽이 규칙인지 알 수 없다
--
-- nullable 이다 — 사업자등록번호는 선택 입력이고(API 7.1 필수 표시 없음),
-- 기존 행에 채울 값도 없다.
ALTER TABLE core.business
    ADD COLUMN registration_number_masked VARCHAR(32);
