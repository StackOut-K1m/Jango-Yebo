-- =============================================================================
-- REPORT — 주간·월간 지표와 AI 브리핑 스냅샷 (ERD §1.6 · API 15.2 · P1-17)
--
-- **지표와 문장을 한 행에 둔다.** 명세가 「생성 실패 시 status = FAILED 이며 지표
-- (metrics)만이라도 반환한다」고 정했다 — 문장이 없는 브리핑은 오류가 아니라 정상
-- 산출물이다. 나눠 두면 「지표는 있는데 문장이 없는 상태」가 조인 결과로만 표현되어,
-- 화면이 그것을 「아직 안 만들어졌다」와 구분하지 못한다.
--
-- **15.3 월별 리포트도 이 테이블을 쓴다**(ERD 1693행). 그쪽은 metrics 의 모양만
-- 다르고 수명과 키가 같다.
-- =============================================================================

CREATE TABLE core.report (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL,
    report_type  VARCHAR(20)  NOT NULL,
    period_start DATE         NOT NULL,
    period_end   DATE         NOT NULL,
    -- 계산 엔진이 낸 지표와 근거 참조(API metrics[].sourceRef). LLM 은 이 값만 읽고
    -- 여기 없는 수치를 문장에 쓰면 그 문장이 폐기된다(20.7).
    metrics      JSONB        NOT NULL,
    headline     VARCHAR(200),
    narrative    TEXT,
    status       VARCHAR(20)  NOT NULL,
    generated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_report_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_report_type     CHECK (report_type IN ('WEEKLY', 'MONTHLY')),
    -- PENDING 은 ERD 에 없던 값이다. 지표를 저장한 뒤 문장을 기다리는 구간이 실제로
    -- 있는데(202 + 콜백), 그동안을 COMPLETED 로 두면 화면이 문장이 오기도 전에
    -- 「완료」로 읽고, FAILED 로 두면 실패하지도 않은 것이 실패로 보인다.
    CONSTRAINT ck_report_status   CHECK (status IN ('PENDING', 'COMPLETED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_report_period   CHECK (period_start <= period_end),
    -- 같은 주를 다시 돌려도 두 벌이 생기지 않는다. 배치가 재시도돼도 덮어쓴다.
    CONSTRAINT uk_report_period   UNIQUE (business_id, report_type, period_start)
);

CREATE INDEX ix_report_business ON core.report (business_id, period_start DESC);

COMMENT ON COLUMN core.report.narrative IS
    'AI 브리핑 본문. 생성 전·실패 시 null — 지표만으로도 정상 산출물이다 (API 15.2).';

-- =============================================================================
-- JOB 타입에 BRIEFING_GENERATION 을 더한다
--
-- 워커는 /internal/v1/ai/briefing-generation 을 이미 열어 뒀는데(20.7) **그 Job 을
-- 만들 타입이 없었다.** V21 이 PROGRAM_STRUCTURING 을 더할 때와 같은 사정이다.
--
-- CHECK 은 더할 수 없어 지우고 다시 만든다. 기존 9종의 철자를 그대로 옮긴다.
-- 같이 고쳐야 하는 곳 — 공통규약 2.7 · ERD 8장 · JobType enum · 이 CHECK.
-- =============================================================================

ALTER TABLE core.job DROP CONSTRAINT ck_job_type;

ALTER TABLE core.job ADD CONSTRAINT ck_job_type CHECK (job_type IN (
    'ACCOUNT_SYNC', 'TRANSACTION_IMPORT',
    'TRANSACTION_CLASSIFICATION', 'EVIDENCE_EXTRACTION',
    'EXPORT_GENERATION', 'TAX_DRAFT_GENERATION',
    'PRODUCT_SALES_OCR', 'LOAN_SYNC',
    'PROGRAM_STRUCTURING', 'BRIEFING_GENERATION'));
