-- =============================================================================
-- 종합소득세 신고서 초안 (P0-12 · API 14.3 · ERD 1.7)
--
-- **민감 항목 값은 저장하지 않는다.** 주소지(①)·생년월일(④)은 fields 에 키만 있고 값은
-- 항상 null 이다. 사용자는 내보내기 요청 본문에만 실어 보내고, 그 값은 응답 파일에만
-- 존재한다(14.3 export). 감사 로그에는 필드 키와 시각만 남는다.
--
-- **근거 목록을 저장하지 않는다.** 어떤 거래가 어느 항목에 들어갔는지는 요청이 올 때
-- TRANSACTION·TRANSACTION_EVIDENCE 를 category_mapping 으로 다시 조회해 만든다(14.3 basis).
-- fields.basisSummary 는 생성 시점의 건수 스냅샷일 뿐이다.
--
-- **재생성마다 새 행이다.** 같은 기간에 유일 제약을 두지 않는다 — 검토 상태가 바뀌면
-- 이전 초안은 STALE 로 남고 새 행이 생긴다(이력).
--
-- ERD 표와 다른 곳 하나: created_at 을 둔다. 표에는 updated_at 만 있는데, 저장소의 모든
-- 업무 테이블이 BaseEntity(ERD 1.1 공통 감사 컬럼)를 쓰고 있어 혼자 빠지면 엔티티가
-- 그 상속을 못 받는다.
-- =============================================================================

CREATE TABLE core.tax_filing_draft (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id           BIGINT        NOT NULL,
    template_id           BIGINT        NOT NULL,

    -- 생성 Job(TAX_DRAFT_GENERATION). 행을 먼저 만들고 Job 을 거는 순서라 Optional 이다.
    job_id                BIGINT,

    tax_year              INT           NOT NULL,
    period_start          DATE          NOT NULL,
    period_end            DATE          NOT NULL,
    status                VARCHAR(20)   NOT NULL DEFAULT 'PROCESSING',

    -- 사용자가 홈택스 신고도움서비스에서 옮겨 적은 참고값. 서비스는 신고 유형·기장의무를
    -- 판정하지 않고 표시와 대사에만 쓴다(14.3).
    hometax_reference     JSONB,

    -- 필드별 value·source·status·basisSummary·reviewNote. 민감 필드는 값이 항상 null.
    fields                JSONB         NOT NULL DEFAULT '{}'::jsonb,

    -- 사용자 수정값·메모. **집계값과 분리 보관한다** — 한 칸에 덮어쓰면 근거 추적이 끊긴다.
    overrides             JSONB,

    -- 개인 사용 제외·확인 필요·미분류 합계.
    excluded_summary      JSONB,

    -- 생성 시점 검토 확정률. 100% 가 아니어도 생성할 수 있다(14.3).
    based_on_review_rate  NUMERIC(5,4)  NOT NULL DEFAULT 0,

    generated_at          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_tfd_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT fk_tfd_template FOREIGN KEY (template_id) REFERENCES core.tax_form_template (id),
    CONSTRAINT fk_tfd_job      FOREIGN KEY (job_id)      REFERENCES core.job (id),

    CONSTRAINT ck_tfd_status CHECK (status IN ('PROCESSING', 'READY', 'STALE', 'FAILED')),
    CONSTRAINT ck_tfd_period CHECK (period_end >= period_start),
    CONSTRAINT ck_tfd_rate   CHECK (based_on_review_rate BETWEEN 0 AND 1)
);

COMMENT ON TABLE core.tax_filing_draft IS '종합소득세 신고서 초안 (항목 값·근거 요약 JSONB. 민감 항목 값은 저장하지 않는다)';

-- 목록(14.3 GET /businesses/{id}/tax-drafts?taxYear=)은 최신순이다.
CREATE INDEX ix_tfd_business_year ON core.tax_filing_draft (business_id, tax_year, id DESC);

-- 진행 중 초안 조회. 같은 (사업장·연도·서식)에 PROCESSING 이 있으면 그것을 돌려주므로
-- (중복 요청 처리) 이 경로가 매 생성 요청마다 돈다.
CREATE INDEX ix_tfd_processing ON core.tax_filing_draft (business_id, tax_year, template_id)
    WHERE status = 'PROCESSING';
