    expected_amount_min NUMERIC(19,4) NOT NULL,
    expected_amount_max NUMERIC(19,4) NOT NULL,
    next_expected_date  DATE,
    confidence          NUMERIC(5,4)  NOT NULL,
    status              VARCHAR(20)   NOT NULL DEFAULT 'CANDIDATE',
    confirmed_by        BIGINT,
    confirmed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_rp_business  FOREIGN KEY (business_id)  REFERENCES core.business (id),
    CONSTRAINT fk_rp_account   FOREIGN KEY (account_id)   REFERENCES core.account (id),
    CONSTRAINT fk_rp_category  FOREIGN KEY (category_id)  REFERENCES core.transaction_category (id),
