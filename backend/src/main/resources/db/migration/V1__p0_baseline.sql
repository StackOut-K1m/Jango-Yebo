-- ERD의 USER. PostgreSQL 예약어라 테이블명만 users 로 둔다(유일한 명명 예외).
CREATE TABLE core.users (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    name                VARCHAR(100) NOT NULL,
    phone               VARCHAR(20),
    -- 금융망 userKey. 사실상 계좌 접근권이므로 애플리케이션 레벨에서 암호화해 저장한다.
    -- 가입 시 발급 실패하면 null로 두고 계좌 연결 시 재시도한다.
    fin_user_key        VARCHAR(512),
    default_business_id BIGINT,
    system_role         VARCHAR(20)  NOT NULL DEFAULT 'USER',
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_system_role CHECK (system_role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status      CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE TABLE core.business (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id       BIGINT       NOT NULL,
    name                VARCHAR(100) NOT NULL,
    registration_number VARCHAR(64),          -- 암호화 저장, 응답은 마스킹
    industry_code       VARCHAR(30),
    region              VARCHAR(50),
    taxation_type       VARCHAR(20)  NOT NULL DEFAULT 'GENERAL',
    opened_on           DATE,
    annual_revenue      NUMERIC(19,4),
    employee_count      INT,
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    deleted_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_business_owner    FOREIGN KEY (owner_user_id) REFERENCES core.users (id),
    CONSTRAINT ck_business_taxation CHECK (taxation_type IN ('GENERAL', 'SIMPLIFIED')),
    CONSTRAINT ck_business_status   CHECK (status IN ('ACTIVE', 'CLOSED'))
);

-- users ↔ business 순환 FK. users 를 먼저 만들어야 해서 여기서 건다.
ALTER TABLE core.users
    ADD CONSTRAINT fk_users_default_business
    FOREIGN KEY (default_business_id) REFERENCES core.business (id);

CREATE INDEX ix_business_owner ON core.business (owner_user_id) WHERE deleted_at IS NULL;

CREATE TABLE core.account (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id              BIGINT       NOT NULL,
    provider                 VARCHAR(20)  NOT NULL DEFAULT 'SSAFY_FIN',
    bank_code                VARCHAR(10)  NOT NULL,
    -- 금융망 호출(동기화·1원 인증·잔액)에 원문이 필요하므로 암호화 저장한다.
    account_number_encrypted VARCHAR(512) NOT NULL,
    -- 중복 연결 방지(ACCOUNT_ALREADY_LINKED). 암호문은 매번 달라지므로 해시로 비교한다.
    account_number_hash      VARCHAR(128) NOT NULL,
    account_number_masked    VARCHAR(32)  NOT NULL,
    name                     VARCHAR(100) NOT NULL,
    is_primary               BOOLEAN      NOT NULL DEFAULT FALSE,
    status                   VARCHAR(30)  NOT NULL DEFAULT 'PENDING_VERIFICATION',
    verified_at              TIMESTAMPTZ,
    current_balance          NUMERIC(19,4),   -- 1원 인증 완료 전 null
    balance_as_of            TIMESTAMPTZ,
    last_synced_at           TIMESTAMPTZ,
    sync_status              VARCHAR(20)  NOT NULL DEFAULT 'NEVER',
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_account_business  FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT uk_account_number    UNIQUE (account_number_hash),
    CONSTRAINT ck_account_status    CHECK (status IN ('PENDING_VERIFICATION', 'CONNECTED',
                                                      'VERIFICATION_EXPIRED', 'DISCONNECTED')),
    CONSTRAINT ck_account_sync      CHECK (sync_status IN ('NEVER', 'RUNNING', 'SUCCESS', 'FAILED'))
);

CREATE INDEX ix_account_business ON core.account (business_id, status);


