    CONSTRAINT ck_rp_cadence   CHECK (cadence_type IN ('WEEKLY', 'MONTHLY', 'INTERVAL')),
    CONSTRAINT ck_rp_holiday   CHECK (holiday_rule IN ('NEXT_BUSINESS_DAY', 'PREVIOUS_BUSINESS_DAY', 'NONE')),
    CONSTRAINT ck_rp_status    CHECK (status IN ('CANDIDATE', 'CONFIRMED', 'DISMISSED', 'PAUSED')),
    CONSTRAINT ck_rp_amount    CHECK (expected_amount_min <= expected_amount_max),
    CONSTRAINT ck_rp_dom       CHECK (day_of_month IS NULL OR day_of_month BETWEEN 1 AND 31),
    CONSTRAINT ck_rp_dow       CHECK (day_of_week  IS NULL OR day_of_week  BETWEEN 1 AND 7),
    CONSTRAINT ck_rp_conf      CHECK (confidence >= 0 AND confidence <= 1)
    -- 적중률(hitRate)은 저장하지 않고 planned_transaction 매칭 결과에서 집계한다.
);

CREATE INDEX ix_rp_business ON forecast.recurring_pattern (business_id, status);

-- 모든 출처(사용자·패턴·세금·대출)의 통합 예정 거래. 예측 계산의 단일 입력이다.
CREATE TABLE forecast.planned_transaction (
    id                     BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id            BIGINT        NOT NULL,
    account_id             BIGINT,
    category_id            BIGINT,
    source_type            VARCHAR(20)   NOT NULL,
    recurring_pattern_id   BIGINT,
    created_by             BIGINT,       -- 시스템 생성이면 null
    name                   VARCHAR(100)  NOT NULL,
    expected_date          DATE          NOT NULL,   -- 공휴일 보정 후
    original_expected_date DATE          NOT NULL,   -- 보정 전. 다르면 보정이 적용된 것
    flow_type              VARCHAR(20)   NOT NULL,
    amount_expected        NUMERIC(19,4) NOT NULL,
    amount_min             NUMERIC(19,4) NOT NULL,
    amount_max             NUMERIC(19,4) NOT NULL,
    status                 VARCHAR(20)   NOT NULL DEFAULT 'EXPECTED',
    matched_transaction_id BIGINT,
    matched_date_diff_days INT,
    matched_amount_diff    NUMERIC(19,4),
    memo                   TEXT,
    version                INT           NOT NULL DEFAULT 0,   -- optimistic locking
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_pt_business FOREIGN KEY (business_id)            REFERENCES core.business (id),
    CONSTRAINT fk_pt_account  FOREIGN KEY (account_id)             REFERENCES core.account (id),
    CONSTRAINT fk_pt_category FOREIGN KEY (category_id)            REFERENCES core.transaction_category (id),
    CONSTRAINT fk_pt_pattern  FOREIGN KEY (recurring_pattern_id)   REFERENCES forecast.recurring_pattern (id),
    CONSTRAINT fk_pt_user     FOREIGN KEY (created_by)             REFERENCES core.users (id),
    CONSTRAINT fk_pt_matched  FOREIGN KEY (matched_transaction_id) REFERENCES core.transaction (id),
    CONSTRAINT ck_pt_source   CHECK (source_type IN ('USER', 'PATTERN', 'TAX', 'LOAN')),
    CONSTRAINT ck_pt_flow     CHECK (flow_type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_pt_status   CHECK (status IN ('EXPECTED', 'CONFIRMED', 'MATCHED', 'MISSED', 'CANCELLED')),
    CONSTRAINT ck_pt_amount   CHECK (amount_min <= amount_expected AND amount_expected <= amount_max),
    CONSTRAINT ck_pt_positive CHECK (amount_min > 0)
);

-- 실제 거래 하나는 하나의 예정 거래에만 매칭된다 (MATCH_CONFLICT).
CREATE UNIQUE INDEX uk_pt_matched ON forecast.planned_transaction (matched_transaction_id)
    WHERE matched_transaction_id IS NOT NULL;
-- 예측 계산의 주 조회 경로
CREATE INDEX ix_pt_business_date ON forecast.planned_transaction (business_id, expected_date, status);
CREATE INDEX ix_pt_pattern       ON forecast.planned_transaction (recurring_pattern_id)
    WHERE recurring_pattern_id IS NOT NULL;

