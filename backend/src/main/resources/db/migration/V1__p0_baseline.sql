-- API 8.1의 고정 23종. 계층 없는 flat 시드 데이터이며 값은 V2에서 넣는다.
-- 추가·비활성(active=false)·개명은 배포 없이 가능하지만 code 는 안정 식별자다
-- (규칙셋·LLM few-shot·분류 이력이 code 에 묶인다).
CREATE TABLE core.transaction_category (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(50)  NOT NULL,
    flow_type  VARCHAR(20)  NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order INT          NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_category_code   UNIQUE (code),
    CONSTRAINT ck_category_flow   CHECK (flow_type IN ('DEPOSIT', 'WITHDRAWAL'))
);

CREATE TABLE core.transaction (
    id                        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id               BIGINT        NOT NULL,
    account_id                BIGINT        NOT NULL,
    category_id               BIGINT,
    -- 금융망 transactionUniqueNo. 계좌 내 유일하므로 그대로 중복 제거 키가 된다.
    external_transaction_id   VARCHAR(64),
    -- CSV 전용. (거래일시, 방향, 금액, 적요) 해시 — 금융망 경로에서는 사용하지 않는다.
    -- 방향이 빠지면 같은 시각·같은 금액의 입금과 출금이 하나로 뭉개져 한 건이 유실된다
    -- (계좌 간 이체가 한 파일에 담기면 실제로 발생). API 7.4 v1.4에서 정정됐다.
    deduplication_key         VARCHAR(128),
    source_type               VARCHAR(20)   NOT NULL,
    occurred_at               TIMESTAMPTZ   NOT NULL,
    transaction_date          DATE          NOT NULL,
    flow_type                 VARCHAR(20)   NOT NULL,
    amount                    NUMERIC(19,4) NOT NULL,
    balance_after             NUMERIC(19,4),
    description               VARCHAR(255),   -- 금융망 transactionSummary. 분류의 거의 유일한 근거
    counterparty_name         VARCHAR(100),
    counterparty_account_no   VARCHAR(32),
    classification_status     VARCHAR(20)   NOT NULL DEFAULT 'UNCLASSIFIED',
    classification_confidence NUMERIC(5,4),
    needs_confirmation        BOOLEAN       NOT NULL DEFAULT FALSE,
    -- 예측·집계 제외(반복 패턴 학습·잔액 곡선). 세무상 필요경비 제외는 tax_review_status 가
    -- 담당하며 둘은 독립이다 — 장비 구입은 예측에서 빼되 경비로 인정될 수 있고,
    -- 개인 사용 지출은 경비에서 빼되 예측에는 반영해야 한다 (API 8.2).
    is_excluded               BOOLEAN       NOT NULL DEFAULT FALSE,
    -- 종합소득세 검토 상태 (API 8.7). 출금 사실만으로 필요경비 인정이 확정되지 않는다.
    tax_review_status         VARCHAR(30)   NOT NULL DEFAULT 'UNREVIEWED',
    tax_review_note           TEXT,          -- memo(현금흐름용)와 분리한다
    tax_reviewed_at           TIMESTAMPTZ,   -- 사용자 확정 시각. 자동 판정분은 null
    memo                      TEXT,
    created_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_tx_business   FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT fk_tx_account    FOREIGN KEY (account_id)  REFERENCES core.account (id),
    CONSTRAINT fk_tx_category   FOREIGN KEY (category_id) REFERENCES core.transaction_category (id),
    CONSTRAINT ck_tx_source     CHECK (source_type IN ('FIN_API', 'CSV')),
    CONSTRAINT ck_tx_flow       CHECK (flow_type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_tx_status     CHECK (classification_status IN ('UNCLASSIFIED', 'SUGGESTED', 'CONFIRMED')),
    CONSTRAINT ck_tx_amount     CHECK (amount > 0),   -- 부호 없음. 방향은 flow_type
    CONSTRAINT ck_tx_confidence CHECK (classification_confidence IS NULL
                                       OR (classification_confidence >= 0 AND classification_confidence <= 1)),
    -- API 8.7의 8종. EVIDENCE_* 는 증빙 연결 여부로 자동 판정, 나머지는 사용자 지정.
    -- ASSET_REVIEW 는 값만 예약(화면 P2)이나 CHECK 에는 넣는다 — 나중에 값을 추가하면
    -- 제약 재생성이 필요하고, 그건 배포 후 금지 목록에 해당한다.
    CONSTRAINT ck_tx_tax_review CHECK (tax_review_status IN ('UNREVIEWED', 'EVIDENCE_CONFIRMED',
                                                             'EVIDENCE_MISSING', 'BUSINESS_USE_UNCLEAR',
                                                             'PERSONAL_SUSPECTED', 'DUPLICATE_SUSPECTED',
                                                             'EXPERT_REVIEW', 'ASSET_REVIEW'))
);

-- 중복 수집 방지. 두 경로가 서로 다른 키를 쓰므로 부분 유일 인덱스 2개로 나눈다.
CREATE UNIQUE INDEX uk_tx_external ON core.transaction (account_id, external_transaction_id)
    WHERE external_transaction_id IS NOT NULL;
CREATE UNIQUE INDEX uk_tx_dedup    ON core.transaction (account_id, deduplication_key)
    WHERE deduplication_key IS NOT NULL;

CREATE INDEX ix_tx_business_date  ON core.transaction (business_id, transaction_date DESC, id DESC);
CREATE INDEX ix_tx_account_time   ON core.transaction (account_id, occurred_at DESC);
CREATE INDEX ix_tx_unclassified   ON core.transaction (business_id, classification_status, transaction_date DESC);
-- 확인 센터(SC-02-2) 조회용
CREATE INDEX ix_tx_needs_confirm  ON core.transaction (business_id, transaction_date DESC)
    WHERE needs_confirmation = TRUE;

-- append-only. 분류 감사이자 LLM few-shot 원천이다.
CREATE TABLE core.transaction_classification_history (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id       BIGINT      NOT NULL,
    previous_category_id BIGINT,
    new_category_id      BIGINT,
    changed_by           BIGINT,     -- 시스템 변경이면 null
    classifier_type      VARCHAR(20) NOT NULL,
    previous_status      VARCHAR(20) NOT NULL,
    new_status           VARCHAR(20) NOT NULL,
    confidence           NUMERIC(5,4),
    reason               JSONB,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_tch_transaction FOREIGN KEY (transaction_id)       REFERENCES core.transaction (id),
    CONSTRAINT fk_tch_prev_cat    FOREIGN KEY (previous_category_id) REFERENCES core.transaction_category (id),
    CONSTRAINT fk_tch_new_cat     FOREIGN KEY (new_category_id)      REFERENCES core.transaction_category (id),
    CONSTRAINT fk_tch_user        FOREIGN KEY (changed_by)           REFERENCES core.users (id),
    CONSTRAINT ck_tch_classifier  CHECK (classifier_type IN ('RULE', 'DICTIONARY', 'LLM', 'USER'))
);

CREATE INDEX ix_tch_transaction ON core.transaction_classification_history (transaction_id, created_at DESC);
-- few-shot 구성: 사용자가 확정한 최신 사례를 뽑는다
CREATE INDEX ix_tch_fewshot ON core.transaction_classification_history (created_at DESC)
    WHERE classifier_type = 'USER';


