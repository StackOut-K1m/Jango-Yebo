-- API 2.7 Job 폴링. 전용 EXPORT_JOB 테이블은 이 테이블로 일반화했다.
-- 워커는 SELECT ... FOR UPDATE SKIP LOCKED 로 QUEUED 행을 집는다.
CREATE TABLE core.job (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT      NOT NULL,
    requested_by  BIGINT,     -- 시스템 배치면 null
    job_type      VARCHAR(40) NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    progress      NUMERIC(5,4),
    params        JSONB,
    result        JSONB,
    error_code    VARCHAR(50),
    error_message TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at    TIMESTAMPTZ,   -- 타임아웃 스위퍼 기준 (backend-architecture.md §7.2)
    completed_at  TIMESTAMPTZ,
    CONSTRAINT fk_job_business FOREIGN KEY (business_id)  REFERENCES core.business (id),
    CONSTRAINT fk_job_user     FOREIGN KEY (requested_by) REFERENCES core.users (id),
    -- API 2.7의 8종. ERD §1.4는 PRODUCT_SALES_OCR 이 빠진 7종이지만 API 14.6이
    -- 실제로 이 타입을 쓰므로 API 를 따른다.
    CONSTRAINT ck_job_type     CHECK (job_type IN ('ACCOUNT_SYNC', 'TRANSACTION_IMPORT',
                                                   'TRANSACTION_CLASSIFICATION', 'EVIDENCE_EXTRACTION',
                                                   'EXPORT_GENERATION', 'TAX_DRAFT_GENERATION',
                                                   'PRODUCT_SALES_OCR', 'LOAN_SYNC')),
    CONSTRAINT ck_job_status   CHECK (status IN ('QUEUED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_job_progress CHECK (progress IS NULL OR (progress >= 0 AND progress <= 1))
);

-- 워커 폴링용. QUEUED 만 인덱싱해 크기를 작게 유지한다.
CREATE INDEX ix_job_queue ON core.job (job_type, created_at) WHERE status = 'QUEUED';
-- AI 콜백 유실 감지 스위퍼용
CREATE INDEX ix_job_running ON core.job (started_at) WHERE status = 'PROCESSING';
CREATE INDEX ix_job_business ON core.job (business_id, created_at DESC);

-- 범용 인앱 알림. core 에 두는 이유: CASH_GAP·SAFETY_LINE 은 forecast 에서,
-- SETTLEMENT_MISMATCH·EVIDENCE_MISSING 은 core 에서 발생한다.
-- 모듈 의존은 forecast → core 단방향만 허용하므로 공용 테이블은 core 가 소유해야 한다.
CREATE TABLE core.alert (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL,
    alert_type  VARCHAR(30)  NOT NULL,
    risk_level  VARCHAR(20),
    title       VARCHAR(200) NOT NULL,
    message     TEXT         NOT NULL,
    related_ref JSONB,
    -- 공백 알림이면 최초 부족일·최대 부족액·회복일·원인·대응 제안.
    -- 화면 SC-03-2 공백 상세(/dashboard/gaps/{cashGapId})의 데이터 원천이며
    -- 이 테이블의 id 가 cashGapId 다. 공백 구간 자체는 곡선에서 조회 시 계산한다.
    detail      JSONB,
    dedup_key   VARCHAR(200),
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_alert_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_alert_type     CHECK (alert_type IN ('CASH_GAP', 'SAFETY_LINE', 'RESERVE_SHORTFALL',
                                                       'SETTLEMENT_MISMATCH', 'PATTERN_CANDIDATE',
                                                       'EVIDENCE_MISSING')),
    CONSTRAINT ck_alert_risk     CHECK (risk_level IS NULL OR risk_level IN ('SAFE', 'CAUTION', 'DANGER', 'GAP')),
    CONSTRAINT ck_alert_status   CHECK (status IN ('ACTIVE', 'ACKNOWLEDGED'))
);

-- 같은 원인의 알림은 새로 쌓지 않고 갱신한다.
