CREATE TABLE forecast.forecast_run (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id      BIGINT      NOT NULL,
    base_at          TIMESTAMPTZ NOT NULL,   -- API baseTime
    start_date       DATE        NOT NULL,
    end_date         DATE        NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    -- 계산 엔진 버전 + 모델 아티팩트 버전 `engine-<x.y>/<model>-<ver>` (ERD v1.9, API 10.1).
    -- 모델 미사용 실행은 `engine-1.2/none`.
    -- VARCHAR(20) 이었으나 명세 예시 `engine-1.2/timesfm-2.5-200m` 가 27자라 들어가지 않았다.
    model_version    VARCHAR(60) NOT NULL,
    applied_options  JSONB,
    -- 실행 당시 계좌별 시작 잔액 [{accountId, balance, asOf}]
    opening_balances JSONB       NOT NULL,
    -- 요약 + 반영 항목 스냅샷 + 보정 내역. v1.1에서 제거한 FORECAST_ITEM 의
    -- 감사 추적 역할을 대신한다. 원본이 나중에 바뀌어도 이 값은 불변이다.
    basis            JSONB       NOT NULL,
    completed_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_fr_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_fr_status   CHECK (status IN ('QUEUED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_fr_period   CHECK (start_date <= end_date)
);

-- 조회 API는 최신 COMPLETED 실행을 읽기만 한다 (계산 금지).
CREATE INDEX ix_fr_latest ON forecast.forecast_run (business_id, base_at DESC)
    WHERE status = 'COMPLETED';
-- 30일 경과분 정리 배치용. SCENARIO 는 재계산 모델이라 실행을 참조하지 않으므로
-- 참조 확인 없이 기간만 보고 지우면 된다.
CREATE INDEX ix_fr_cleanup ON forecast.forecast_run (created_at);

CREATE TABLE forecast.daily_balance_forecast (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_run_id     BIGINT        NOT NULL,
    forecast_date       DATE          NOT NULL,
    balance_min         NUMERIC(19,4) NOT NULL,
    balance_expected    NUMERIC(19,4) NOT NULL,
    balance_max         NUMERIC(19,4) NOT NULL,
    -- 원장(예정 거래) + 잔여(모델) 합계다.
    expected_deposit    NUMERIC(19,4) NOT NULL DEFAULT 0,
    expected_withdrawal NUMERIC(19,4) NOT NULL DEFAULT 0,
    -- 위 합계 중 잔여 흐름 모델 기여분(q50). 모델 미적용 실행은 0 (ERD v1.9).
    -- ⚠ 합계에 이미 포함된 값의 내역이지 별도 항이 아니다. 곡선을 그릴 때 더하면 이중 계상이다.
    --   화면의 "모델 반영분" 표시와 정확도 리포트의 베이스라인 대비 비교에 쓴다.
    residual_deposit    NUMERIC(19,4) NOT NULL DEFAULT 0,
    residual_withdrawal NUMERIC(19,4) NOT NULL DEFAULT 0,
    confidence          NUMERIC(5,4)  NOT NULL,
    CONSTRAINT fk_dbf_run   FOREIGN KEY (forecast_run_id) REFERENCES forecast.forecast_run (id) ON DELETE CASCADE,
    CONSTRAINT uk_dbf_date  UNIQUE (forecast_run_id, forecast_date),
    CONSTRAINT ck_dbf_range CHECK (balance_min <= balance_expected AND balance_expected <= balance_max),
    CONSTRAINT ck_dbf_conf  CHECK (confidence >= 0 AND confidence <= 1)
    -- riskLevel 과 정산 공백 구간은 안전선과 비교한 파생값이므로 저장하지 않는다.
);


