--       날짜 = DATE (Asia/Seoul 기준) / 상태값 = VARCHAR + CHECK
--
-- ⚠ 마이그레이션 작성 규칙 (backend-architecture.md §5)
--   허용: 컬럼 추가(nullable/default), 인덱스 추가, 새 테이블
--   금지: 컬럼·테이블 삭제, NOT NULL 추가, 타입·이름 변경 → 다음 릴리스로 분리
--   롤백("이전 태그 재배포")이 깨지지 않게 하기 위한 규칙이다.
