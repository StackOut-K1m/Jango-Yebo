-- =============================================================================
-- 대출·신용 (P1-13·P1-14)
--
-- 네 테이블을 한 번에 만든다. 서로를 참조하지는 않지만 같은 기능에서 같이 쓰이고,
-- 나눠 놓으면 둘만 적용된 DB 가 생긴다.
--
--   loan             보유 대출 (LOAN_08 동기화 + 수동 등록)
--   loan_repayment   회차별 상환 일정·결과 (LOAN_09)
--   loan_product     금융망 대출 상품 (LOAN_03) — 추천의 후보군
--   credit_snapshot  자산 기반 신용등급 이력 (LOAN_04)
--
-- 그리고 planned_transaction 에 loan_id 를 단다. source_type 의 'LOAN' 은 P0 베이스라인
-- (V1 ck_pt_source)부터 있었는데 가리킬 대출이 없었다.
--
-- -----------------------------------------------------------------------------
-- **상환이 매일이다.** 여기가 이 마이그레이션에서 제일 중요한 사실이다.
--
-- 금융망 플로우 문서: "개설일 다음날부터 매일 (대출금+이자)/대출기간 으로 계산되어
-- 오전 08:30 에 수시입출금 계좌에서 상환됩니다." 대출 기간은 2~365일이고 다년 대출이 없다.
-- 이자는 단리 일할이다 — 원금 × (금리/100) × (기간/365).
--
-- 우리 목업은 「9월 10일 대출 상환 1,680,000원」처럼 월 1회 큰 금액으로 그렸다.
-- 총액은 비슷하지만 곡선 모양이 완전히 다르다 — 월 1회는 그날 절벽이고, 매일은
-- 완만한 우하향이다. **월 1회로 모델링하면 자동이체 실패를 못 맞춘다.** 금융망은 매일
-- 빼고 매일 실패를 판정하는데, 월말에 한 번 보는 곡선은 15일에 잔액이 상환액 아래로
-- 내려가는 것을 못 본다. 그 실패가 이 제품이 막으려는 사건이다.
--
-- 그래서 repayment_cycle 의 기본값을 DAILY 로 둔다(2026-09-15 확정,
-- 기능별_기술스택_선정.md 12장 「대출 상환 주기」 해소). 화면에서 묶어 보여주는 것은
-- 표시의 문제이고, 곡선은 매일 계산한다.
-- =============================================================================

-- 보유 대출. 마이너스통장 컬럼(credit_limit·used_amount·accrued_interest)을 같이 두지만
-- P1 에서는 TERM_LOAN 만 채운다 — 기술스택 4.13 이 마이너스통장을 보류로 정리했다.
CREATE TABLE core.loan (
    id                     BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id            BIGINT        NOT NULL,
    loan_type              VARCHAR(20)   NOT NULL DEFAULT 'TERM_LOAN',
    source                 VARCHAR(20)   NOT NULL DEFAULT 'FIN_API',
    -- 금융망 대출 계좌번호. 동기화 중복 방지 키다.
    external_loan_no       VARCHAR(32),
    lender_name            VARCHAR(50)   NOT NULL,
    product_name           VARCHAR(100)  NOT NULL,
    -- ⚠ 금융망은 원금을 주지 않는다. LOAN_08 의 loanBalance 는 「(원금 + 이자) 대출금」이다.
    -- 역산할 수는 있지만 이자가 반올림된 값이라 정확히 되돌아오지 않는다 — 금융망이 주지
    -- 않은 숫자를 지어내지 않는다. FIN_API 대출은 principal_amount 가 null 이다.
    principal_amount       NUMERIC(19,4),   -- 수동 등록만. 마이너스통장도 null
    total_repayable        NUMERIC(19,4),   -- LOAN_08 loanBalance — 원금+이자. 일 상환액의 분자다
    outstanding_balance    NUMERIC(19,4),   -- LOAN_09 remainingLoanBalance — 남은 원금+이자
    credit_limit           NUMERIC(19,4),   -- 마이너스통장 한도
    used_amount            NUMERIC(19,4),
    accrued_interest       NUMERIC(19,4),
    interest_rate          NUMERIC(6,3)  NOT NULL,   -- 연 %. 금융망은 0.1~20
    repayment_cycle        VARCHAR(20)   NOT NULL DEFAULT 'DAILY',
    repayment_type         VARCHAR(30),             -- 수동 등록용(원리금균등 등)
    monthly_payment_day    INT,                     -- MONTHLY·INTEREST_MONTHLY 만
    monthly_payment_amount NUMERIC(19,4),
    -- 상환금이 빠지는 계좌. 이 계좌의 잔액 예측에 반영된다.
    withdrawal_account_id  BIGINT,
    started_on             DATE          NOT NULL,
    maturity_date          DATE          NOT NULL,
    overdue_days           INT,
    status                 VARCHAR(20)   NOT NULL DEFAULT 'NORMAL',
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_loan_business FOREIGN KEY (business_id)           REFERENCES core.business (id),
    CONSTRAINT fk_loan_account  FOREIGN KEY (withdrawal_account_id) REFERENCES core.account (id),
    CONSTRAINT ck_loan_type     CHECK (loan_type IN ('TERM_LOAN', 'MINUS_ACCOUNT')),
    CONSTRAINT ck_loan_source   CHECK (source IN ('MANUAL', 'FIN_API')),
    CONSTRAINT ck_loan_cycle    CHECK (repayment_cycle IN ('DAILY', 'MONTHLY', 'INTEREST_MONTHLY')),
    -- 금융망 개설/상환중/연체 + 우리가 만드는 CLOSED. 금융망에는 CLOSED 가 없다 —
    -- LOAN_08 의 status 는 3종뿐이라 만기·완납 판정은 우리 몫이다.
    CONSTRAINT ck_loan_status   CHECK (status IN ('NORMAL', 'REPAYING', 'OVERDUE', 'CLOSED')),
    CONSTRAINT ck_loan_period   CHECK (maturity_date >= started_on),
    -- 월 상환일은 MONTHLY 계열에만 있다. DAILY 에 값이 있으면 어느 쪽을 믿을지 알 수 없다.
    CONSTRAINT ck_loan_monthly  CHECK (repayment_cycle = 'DAILY' OR monthly_payment_day IS NOT NULL)
);

-- 같은 대출을 두 번 동기화하지 않는다. 수동 등록은 external_loan_no 가 없어 제외한다.
CREATE UNIQUE INDEX uk_loan_external ON core.loan (business_id, external_loan_no)
    WHERE external_loan_no IS NOT NULL;
CREATE INDEX ix_loan_business ON core.loan (business_id, status);
-- 예정 거래 생성기가 「이 계좌에서 빠지는 대출」을 찾는 경로.
CREATE INDEX ix_loan_account  ON core.loan (withdrawal_account_id)
    WHERE withdrawal_account_id IS NOT NULL;

COMMENT ON COLUMN core.loan.repayment_cycle IS
    'DAILY 가 금융망 대출의 실제 동작이다 — 개설 다음날부터 매일 08:30 에 (대출금+이자)/대출기간 이 빠진다';


-- 회차별 상환. DAILY 대출이면 하루가 한 회차라 1년이면 365행이 된다.
CREATE TABLE core.loan_repayment (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id          BIGINT        NOT NULL,
    installment_no   INT,                       -- 금융망 회차 번호. 수동 등록은 null
    due_date         DATE          NOT NULL,
    -- 금융망은 회차 금액(paymentBalance) 하나만 준다. 원금·이자로 나눠 주지 않아
    -- 두 칸으로 쪼개면 우리가 지어낸 비율이 저장된다 — ERD 는 둘로 나눠 뒀지만 한 칸으로 둔다.
    amount           NUMERIC(19,4) NOT NULL,
    transaction_id   BIGINT,                    -- 실제 출금 거래
    status           VARCHAR(20)   NOT NULL DEFAULT 'SCHEDULED',
    -- LOAN_09 가 주는 실패 사유. 「자동이체 실패 잔액 부족」이 그대로 온다 —
    -- 우리가 막으려던 사건이 실제로 일어났다는 증거라 원문을 남긴다.
    failure_reason   VARCHAR(255),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_lr_loan        FOREIGN KEY (loan_id)        REFERENCES core.loan (id),
    CONSTRAINT fk_lr_transaction FOREIGN KEY (transaction_id) REFERENCES core.transaction (id),
    CONSTRAINT ck_lr_status      CHECK (status IN ('SCHEDULED', 'SUCCESS', 'FAIL')),
    CONSTRAINT ck_lr_amount      CHECK (amount >= 0)
);

-- NULLS NOT DISTINCT 가 필요하다. 수동 등록 대출은 installment_no 가 null 인데,
-- 기본 UNIQUE 는 null 을 서로 다른 값으로 봐서 같은 날짜가 몇 번이든 들어간다.
CREATE UNIQUE INDEX uk_lr_due ON core.loan_repayment (loan_id, due_date, installment_no)
    NULLS NOT DISTINCT;
CREATE INDEX ix_lr_loan_status ON core.loan_repayment (loan_id, status, due_date);


-- 금융망 대출 상품 목록. 추천(16.3)의 후보군이고, 현재 상태만 upsert 한다.
CREATE TABLE core.loan_product (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider          VARCHAR(20)   NOT NULL DEFAULT 'SSAFY_FIN',
    external_id       VARCHAR(32)   NOT NULL,   -- accountTypeUniqueNo
    bank_code         VARCHAR(10)   NOT NULL,
    bank_name         VARCHAR(50)   NOT NULL,
    name              VARCHAR(100)  NOT NULL,
    description       VARCHAR(255),
    loan_type_name    VARCHAR(30)   NOT NULL,
    -- LOAN_03 의 ratingName. 「이 등급 이상이면 가입 가능」이라 최소 등급이다.
    min_grade         VARCHAR(2)    NOT NULL,
    min_loan_balance  NUMERIC(19,4) NOT NULL,
    max_loan_balance  NUMERIC(19,4) NOT NULL,
    interest_rate     NUMERIC(6,3)  NOT NULL,
    loan_period_days  INT           NOT NULL,
    -- 금융망이 주는 이름은 '원리금균등상환' 이지만 실제 계산은 단리 일할 + 매일 자동이체다.
    -- 원문을 저장하되 화면에는 「매일 자동이체」로 쓴다.
    repayment_method  VARCHAR(30)   NOT NULL,
    -- 추천에 내보낼지. **기본이 꺼짐이다.**
    --
    -- 금융망에는 대출 상품 삭제 API 가 없고(LOAN_01~10 어디에도 없다), 팀 apiKey 를 가진
    -- 누구나 LOAN_02 로 상품을 만들 수 있다(tools/fin-console 에 등록 폼이 있다). 동기화가
    -- 목록을 그대로 가져오면 누가 시험 삼아 만든 상품이 사장님에게 「이 대출을 받으세요」로
    -- 나간다. 그래서 새로 나타난 상품은 꺼진 채로 들어오고 사람이 켠 것만 추천에 나간다.
    -- 잘못 등록한 상품을 화면에서 지우는 유일한 수단이기도 하다.
    --
    -- 같은 규칙을 이미 두 곳에서 쓴다 — account.auto_execute_planned(켠 계좌만 실제로
    -- 출금한다)와 ForecastRunService.openingBalance(알 수 없는 잔액은 빼고 더한다).
    recommendable     BOOLEAN       NOT NULL DEFAULT FALSE,
    -- null 이면 아직 검토 안 한 것, 값이 있으면 검토하고 제외한 것이다.
    -- recommendable = FALSE 하나로는 둘을 구분할 수 없다.
    excluded_reason   VARCHAR(100),
    collected_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_lp_external  UNIQUE (provider, external_id),
    CONSTRAINT ck_lp_grade     CHECK (min_grade IN ('A', 'B', 'C', 'D', 'E')),
    CONSTRAINT ck_lp_balance   CHECK (min_loan_balance <= max_loan_balance),
    CONSTRAINT ck_lp_period    CHECK (loan_period_days BETWEEN 2 AND 365)
);

-- 추천 조회의 주 경로. 꺼진 상품이 대다수가 되므로 부분 인덱스로 둔다.
CREATE INDEX ix_lp_recommendable ON core.loan_product (min_grade, interest_rate)
    WHERE recommendable;

COMMENT ON COLUMN core.loan_product.recommendable IS
    '추천 노출 여부. 기본 FALSE — 동기화(LOAN_SYNC)는 이 값을 갱신 대상에서 뺀다';


-- 자산 기반 신용등급 이력. LOAN_04 응답과 1:1 로 맞는다.
CREATE TABLE core.credit_snapshot (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id           BIGINT        NOT NULL,
    grade                 VARCHAR(2)    NOT NULL,
    demand_deposit_asset  NUMERIC(19,4) NOT NULL,
    deposit_savings_asset NUMERIC(19,4) NOT NULL,
    total_asset           NUMERIC(19,4) NOT NULL,
    assessed_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_cs_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_cs_grade    CHECK (grade IN ('A', 'B', 'C', 'D', 'E'))
);

-- 「등급이 언제부터 떨어졌나」를 보여주는 경로. 최신 한 건이 대부분의 조회다.
CREATE INDEX ix_cs_business ON core.credit_snapshot (business_id, assessed_at DESC);

COMMENT ON TABLE core.credit_snapshot IS
    '금융망 등급은 수시입출금+예적금 잔액 합계로만 산출된다. 연체 이력도 소득도 반영되지 않으므로 '
    '화면에서 실제 신용등급처럼 보이게 하지 않는다 — 「보유 자산 기준 참고 등급」으로 표기한다';


-- 예정 거래가 어느 대출에서 나왔는지. source_type = 'LOAN' 인 행만 채운다.
ALTER TABLE forecast.planned_transaction
    ADD COLUMN loan_id BIGINT,
    ADD CONSTRAINT fk_pt_loan FOREIGN KEY (loan_id) REFERENCES core.loan (id);

-- 대출 조건이 바뀌면 그 대출이 만든 예정 거래를 찾아 다시 만든다.
CREATE INDEX ix_pt_loan ON forecast.planned_transaction (loan_id) WHERE loan_id IS NOT NULL;

COMMENT ON COLUMN forecast.planned_transaction.loan_id IS
    '생성 출처 대출 (source_type = LOAN). 상환은 매일이라 DAILY 대출 하나가 지평 일수만큼 행을 만든다';
