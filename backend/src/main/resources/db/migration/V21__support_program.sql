-- =============================================================================
-- 지원 제도 공고 (P1-15 · API 17.1~17.3 · ERD 8장)
--
-- 번호 주의 — V19·V20 이 팀원 것이라 V21 이다. **V20 이 develop 에 먼저 들어간 것을 확인했다**
-- (2026-09-15, P1-06 범위 제외). `out-of-order` 를 켜지 않아 순서가 뒤집히면 서버가 안 뜨므로,
-- 다음에 번호를 잡을 때도 develop 에 이미 있는 것과 팀원이 들고 있는 것을 같이 확인한다.
--
-- **공고는 사업장 공용 데이터다.** business_id 가 없는 이유가 이것이다 — 같은 공고를
-- 사업장마다 복제하면 수집과 LLM 구조화 비용이 사업장 수만큼 늘어난다. 맞춤 추천(17.3)은
-- 이 표를 읽어 요청 시 계산하고, 공백 알림에 실은 후보만 ALERT.detail 에 스냅샷으로 남긴다.
--
-- **크롤링하지 않는다. 기업마당 공식 API 로 받는다** (공통규약 23장 결정, 2026-09-15).
-- 중소벤처24·소진공은 robots.txt 가 전면 차단이고 K-Startup 은 공고 목록 경로를 막았다.
--
-- **구조화에 실패해도 행은 남긴다.** 원문과 URL 이 있으면 사람이 원문으로 갈 수 있고,
-- 프롬프트를 고친 뒤 다시 돌릴 수 있다. eligibility 가 비면 검색에서만 빠진다(17.1 폴백).
-- =============================================================================

CREATE TABLE core.support_program (
    id                         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name                VARCHAR(30)   NOT NULL,
    external_id                VARCHAR(100)  NOT NULL,
    title                      VARCHAR(500)  NOT NULL,
    organizer                  VARCHAR(200),
    source_url                 VARCHAR(1000) NOT NULL,
    support_type               VARCHAR(20),
    max_amount                 NUMERIC(19,4),
    interest_rate              NUMERIC(6,4),
    application_start_date     DATE,
    application_end_date       DATE,
    expected_disbursement_days INT,
    eligibility                JSONB         NOT NULL DEFAULT '{}'::jsonb,
    raw_text                   TEXT,
    collected_at               TIMESTAMPTZ   NOT NULL DEFAULT now(),
    status                     VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    created_at                 TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ   NOT NULL DEFAULT now(),

    -- 재수집은 upsert 다. 매일 전량을 받아 같은 공고를 덮어쓴다(공통규약 23장).
    CONSTRAINT uk_sp_source UNIQUE (source_name, external_id),

    -- 17.1 의 supportType 필터 값. **NULL 을 허용한다** — 구조화 전이거나 실패한 공고다.
    CONSTRAINT ck_sp_support_type CHECK (support_type IS NULL OR support_type IN (
        'FUNDING', 'SUBSIDY', 'VOUCHER', 'CONSULTING', 'OTHER')),

    CONSTRAINT ck_sp_status CHECK (status IN ('OPEN', 'CLOSED', 'UPCOMING', 'UNKNOWN')),

    -- 기간이 둘 다 있을 때만 본다. 기업마당 reqstDt 는 선택 항목이고
    -- **상시모집 공고는 비어서 온다** — 거기에 NOT NULL 을 걸면 정상 공고가 반려된다.
    CONSTRAINT ck_sp_period CHECK (
        application_start_date IS NULL
        OR application_end_date IS NULL
        OR application_start_date <= application_end_date),

    CONSTRAINT ck_sp_disbursement CHECK (
        expected_disbursement_days IS NULL OR expected_disbursement_days >= 0)
);

COMMENT ON TABLE core.support_program IS
    '지원사업 공고 수집·구조화 결과 (P1-15). 사업장 공용 데이터라 business_id 가 없다';
COMMENT ON COLUMN core.support_program.source_name IS
    '수집 출처. BIZINFO(기업마당) 로 시작하고 K_STARTUP·SMES 는 확장 단계에 붙인다';
COMMENT ON COLUMN core.support_program.eligibility IS
    '지역·업종·매출 상한·업력·제외 대상·불확실 조건·필수 서류 (17.2). 구조화 전이면 빈 객체다';
COMMENT ON COLUMN core.support_program.raw_text IS
    '공고 원문. LLM 구조화(20.6) 입력이고, 프롬프트를 고쳐 다시 돌릴 때도 이것을 쓴다';
COMMENT ON COLUMN core.support_program.expected_disbursement_days IS
    '예상 집행 소요일. 공백 연계 추천(17.3)이 "언제 들어오나" 를 역산하는 값이다';
COMMENT ON COLUMN core.support_program.collected_at IS
    '수집 시각. 화면에 원문 링크와 함께 항상 병기한다 (17.1)';

-- 17.1 의 기본 화면: 아직 마감되지 않은 공고를 마감 임박순으로 본다.
-- 마감된 공고가 대부분을 차지하게 되므로 부분 인덱스로 살아 있는 것만 담는다.
CREATE INDEX ix_sp_open_deadline
    ON core.support_program (application_end_date, collected_at DESC)
 WHERE status = 'OPEN';

-- 구조화 대기분을 고르는 경로 (20.6). 신규 공고만 LLM 에 보내므로 그 조건이 곧 인덱스다.
CREATE INDEX ix_sp_unstructured
    ON core.support_program (collected_at)
 WHERE eligibility = '{}'::jsonb;

-- =============================================================================
-- JOB.job_type 에 PROGRAM_STRUCTURING 을 더한다 (API 20.6)
--
-- **20.6 요청 본문이 jobId 를 요구하는데 그 Job 을 만들 타입이 없었다.** 공통규약 2.7 ·
-- ERD 8장 · JobType enum · 이 CHECK 네 곳 모두 8종이었다. 네 곳을 같이 고친다.
--
-- CHECK 은 더할 수 없어 지우고 다시 만든다. 기존 8종의 철자를 그대로 옮긴다.
-- =============================================================================

ALTER TABLE core.job DROP CONSTRAINT ck_job_type;

ALTER TABLE core.job ADD CONSTRAINT ck_job_type CHECK (job_type IN (
    'ACCOUNT_SYNC', 'TRANSACTION_IMPORT',
    'TRANSACTION_CLASSIFICATION', 'EVIDENCE_EXTRACTION',
    'EXPORT_GENERATION', 'TAX_DRAFT_GENERATION',
    'PRODUCT_SALES_OCR', 'LOAN_SYNC',
    'PROGRAM_STRUCTURING'));

-- =============================================================================
-- JOB.business_id 를 nullable 로 — 사업장이 없는 작업이 생겼다
--
-- **공고 구조화는 사업장이 없다.** 공고가 사업장 공용 데이터라 한 번 읽으면 모두가 쓴다.
-- NOT NULL 로 두면 위에서 더한 타입을 **쓸 수가 없다** — 아무 사업장이나 골라 넣으면
-- 그 사장님의 Job 목록에 남의 작업이 뜬다.
--
-- `requested_by` 는 이미 같은 이유로 nullable 이다("시스템 배치면 null", V1).
--
-- **소유권 검사는 fail-closed 라 안전하다.** BusinessGuard 가
-- `EXISTS (... WHERE id = ?)` 로 판정하는데 NULL 을 넣으면 술어가 NULL 이라 행이 없고,
-- 결과는 403 이다. 즉 전역 작업은 `GET /jobs/{jobId}` 로 아무에게도 보이지 않는다 —
-- 시스템 배치 작업에 맞는 기본값이다.
--
-- ⚠ 사업장 단위 작업은 여전히 business_id 를 넣어야 한다. 그 강제는 DB 가 아니라
-- 호출부에 있다(JobService.enqueue 인자). FK 는 그대로라 없는 사업장은 계속 막힌다.
-- =============================================================================

ALTER TABLE core.job ALTER COLUMN business_id DROP NOT NULL;

COMMENT ON COLUMN core.job.business_id IS
    '사업장 단위 작업이면 그 사업장. 전역 작업(PROGRAM_STRUCTURING 등)이면 NULL — 소유권 검사가 403 으로 막는다';
