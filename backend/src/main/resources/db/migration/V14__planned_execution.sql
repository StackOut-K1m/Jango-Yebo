-- =============================================================================
-- 예정 거래 자동 반영 (ERD PLANNED_EXECUTION · API 9.6)
--
-- **우리 DB 의 예정 거래를 금융망 계좌에 실제로 흘려보낸다.**
--
-- 지금까지 예정 거래는 우리 DB 에만 있었다. 예정일이 지나도 연결된 금융망 계좌에는
-- 아무 일이 일어나지 않아서, 그 행은 EXPECTED 인 채 곡선 창(오늘~+30일)에서 조용히
-- 빠지고 실제 잔액은 그대로였다. 시연 데이터를 손으로 출금하거나 다시 시드해야 했다.
--
-- **자동 실행 금지 원칙과 충돌하지 않는 이유**(공통규약 23장 예약이체 판정과 같은 갈래):
-- 대상이 사용자 자금이 아니라 **우리가 만든 싸피은행 샌드박스 계좌**이고,
-- `auto_execute_planned` 를 켠 계좌에서만, **사용자가 승인한 반복 패턴**이 만든
-- 예정 거래(source_type = PATTERN)만 재현한다. 기본값은 FALSE 다.
--
-- **원장이 필요한 이유는 돈이 두 번 나가지 않게 하기 위해서다.**
-- 금융망 `institutionTransactionUniqueNo` 는 멱등성 키가 아니라 중복 거부 키이고
-- (FinApiHeaderFactory javadoc), 로컬 DB 와 배포 DB 는 서로를 보지 못한다.
-- 이 테이블이 한 DB 안에서 재기동·재배포를 넘는 「한 번만」을 보증하고,
-- 두 서버 사이는 금융망 거래내역(DD_12) 사전 조회가 맡는다.
-- =============================================================================

-- 계좌 단위 opt-in. 화면에 노출하지 않고 시드 도구와 소유자만 켠다.
ALTER TABLE core.account
    ADD COLUMN auto_execute_planned BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN core.account.auto_execute_planned IS
    '예정 거래를 금융망에 실제로 출금·입금할지. 시연용 샌드박스 계좌에만 켠다(기본 FALSE).';


CREATE TABLE forecast.planned_execution (
    id                                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planned_transaction_id            BIGINT        NOT NULL,
    business_id                       BIGINT        NOT NULL,
    account_id                        BIGINT        NOT NULL,
    -- 패턴 생성분이면 그 패턴. 회차 중복 실행을 막는 부분 UK 의 키다.
    recurring_pattern_id              BIGINT,
    -- 예정일. 실제 거래가 찍히는 날짜와 다를 수 있다 — 금융망은 과거 날짜를 만들지 못해
    -- 따라잡기 실행은 실행한 날로 찍힌다(기술스택 §4.1.1).
    due_date                          DATE          NOT NULL,
    flow_type                         VARCHAR(20)   NOT NULL,
    -- 실제로 보낸 금액. 금융망은 정수 원만 받으므로 예상액을 반올림·클램프한 값이다.
    amount                            NUMERIC(19,4) NOT NULL,
    -- transactionSummary 로 보낸 적요. 예정 거래 name 과 같다.
    summary                           VARCHAR(100)  NOT NULL,
    -- 같은 (예정일, 방향, 금액, 적요) 가 여럿일 때의 순번. 채번과 채택 배정에 함께 쓴다.
    ordinal                           INT           NOT NULL DEFAULT 0,
    -- 우리가 보낸 채번. 결정적이라 재전송에도 같은 값이다.
    institution_transaction_unique_no VARCHAR(20),
    -- 금융망이 돌려준 거래고유번호. core.transaction.external_transaction_id 와 같은 값이고
    -- 이것이 예정 거래에 정확히 붙이는 열쇠다.
    fin_transaction_unique_no         VARCHAR(64),
    fin_transaction_date              DATE,
    status                            VARCHAR(20)   NOT NULL,
    -- DD_12 에서 이미 있는 거래를 주워 온 것이면 TRUE. 다른 서버가 보냈다는 뜻이다.
    adopted                           BOOLEAN       NOT NULL DEFAULT FALSE,
    -- 어느 실행기가 보냈나(hostname+pid). 두 환경이 겹쳤을 때 사후 추적용이다.
    executor_id                       VARCHAR(100),
    fin_code                          VARCHAR(10),
    failure_reason                    TEXT,
    attempt_count                     INT           NOT NULL DEFAULT 0,
    -- FAILED 인데 값이 있으면 그날 이후 재시도, NULL 이면 영구 실패다.
    retry_after                       DATE,
    last_attempt_at                   TIMESTAMPTZ,
    executed_at                       TIMESTAMPTZ,
    created_at                        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_pe_planned  FOREIGN KEY (planned_transaction_id) REFERENCES forecast.planned_transaction (id),
    CONSTRAINT fk_pe_business FOREIGN KEY (business_id)            REFERENCES core.business (id),
    CONSTRAINT fk_pe_account  FOREIGN KEY (account_id)             REFERENCES core.account (id),
    CONSTRAINT fk_pe_pattern  FOREIGN KEY (recurring_pattern_id)   REFERENCES forecast.recurring_pattern (id),
    CONSTRAINT uk_pe_planned  UNIQUE (planned_transaction_id),
    CONSTRAINT ck_pe_status   CHECK (status IN ('SENT', 'EXECUTED', 'MATCHED', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_pe_flow     CHECK (flow_type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_pe_amount   CHECK (amount > 0)
);

-- **같은 패턴의 같은 회차는 한 번만 실행한다.**
-- 달력을 고치면 refreshPlanned 가 미래 예정 거래를 지우고 새 id 로 다시 만든다. 그때
-- 원장 행이 없는 새 행이 생기므로, planned_transaction_id UK 만으로는 같은 회차가 두 번
-- 나갈 수 있다. 돈이 걸린 자리라 DB 가 막는다.
CREATE UNIQUE INDEX uk_pe_pattern_due ON forecast.planned_execution (recurring_pattern_id, due_date)
    WHERE recurring_pattern_id IS NOT NULL;

-- 금융망 거래 하나는 하나의 실행에만 귀속된다(uk_pt_matched 와 같은 성질).
-- 사전 조회가 같은 거래를 두 예정 거래에 채택하는 것을 막는다.
CREATE UNIQUE INDEX uk_pe_fin_tx ON forecast.planned_execution (account_id, fin_transaction_unique_no)
    WHERE fin_transaction_unique_no IS NOT NULL;

-- 실행기가 계좌별로 「열린 것과 재시도할 것」을 훑는 경로.
CREATE INDEX ix_pe_account_status ON forecast.planned_execution (account_id, status, due_date);
-- 정확 매칭이 사업장별 EXECUTED 를 훑는 경로.
CREATE INDEX ix_pe_business_status ON forecast.planned_execution (business_id, status);

COMMENT ON TABLE forecast.planned_execution IS
    '예정 거래를 금융망에 반영한 원장. 한 예정 거래당 한 행이고, 이 테이블이 이중 출금을 막는다.';
COMMENT ON COLUMN forecast.planned_execution.fin_transaction_unique_no IS
    '금융망 거래고유번호. core.transaction.external_transaction_id 와 같은 값이며 정확 매칭의 키다.';
COMMENT ON COLUMN forecast.planned_execution.adopted IS
    'DD_12 에서 이미 있는 거래를 주워 왔으면 TRUE — 다른 서버나 이전 시도가 보낸 것이다.';
