-- =============================================================================
-- 1. PRODUCT_SALES_EXTRACTION — 추출 1회분 (합의 ④)
-- =============================================================================

-- ERD §1.9 에 없던 테이블이다. 나눈 이유는 검산·모델 메타가 <행>이 아니라 <추출> 단위
-- 값이라서다 — 행마다 복사하면 80행짜리 인쇄물에서 같은 JSONB 가 80번 저장되고, 사람이
-- 한 행을 고칠 때마다 어느 사본이 정본인지 알 수 없게 된다. 증빙이
-- EVIDENCE_EXTRACTION / EVIDENCE_ITEM 으로 나뉜 것과 같은 모양이다.
--
-- ⚠ 이 테이블에 <상품 행>은 없다. 14.7 이 "OCR 결과는 후보이며 저장하지 않는다"고 못박았고
--   그 결정은 그대로다 — 행은 사용자가 검토·확정한 뒤 14.4 가 PRODUCT_SALES_PERIOD 에
--   쓴다. 여기 남는 것은 "모델이 무엇을 어떻게 읽었나"(메타·검산·합계 행)뿐이다.
CREATE TABLE core.product_sales_extraction (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT       NOT NULL,
    job_id         BIGINT,

    -- 요구 1. 헤더에 기간이 없으면 셋 다 null 이고 그것이 정상 동작이다.
    -- 촬영 시각으로 추론하면 월중에 뽑은 반달치를 그 달 전체로 오인해 오류 없이 틀린 답이 된다.
    period_start   DATE,
    period_end     DATE,
    -- 'HEADER' 또는 null. 워커는 추론하지 않는다. 사용자 지정('USER')은 14.4 가 받는다.
    period_source  VARCHAR(10),

    capture_type   VARCHAR(10)  NOT NULL,      -- SCREEN · PRINTOUT. 프롬프트와 기대 정확도가 다르다
    model_name     VARCHAR(100) NOT NULL,
    -- 워커는 항상 null 을 보낸다. V6 의 evidence_extraction 과 같은 이유다.
    model_version  VARCHAR(100),
    prompt_version VARCHAR(100),
    pipeline       VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,

    -- 요구 3. 인쇄물에 실제로 있던 열. 없는 열을 0 으로 채우지 않기 위한 근거다 —
    -- 58mm 는 상품명·수량·결제금액·구성비 4열만 남는다(실측 30표본 전부).
    columns_detected JSONB,

    -- 요구 2. 합계 행 원본. 체크섬(항목 합 vs 합계 행)의 재료이며 14.4 가 대조한다.
    printed_total  JSONB,

    -- ④ 워커 data.validation 을 가공 없이. checksum_status 와 <다른 검사>다 —
    --    이쪽은 행 안의 산술 4식(v1.18), 저쪽은 행이 빠졌는지.
    --    검산 필드가 계약 개정마다 늘어나(v1.14 세율 · v1.15 정렬 · v1.18 매출)
    --    컬럼으로 펴면 마이그레이션이 개정마다 따라붙는다.
    validation     JSONB,

    warnings       JSONB,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_ps_extraction_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_ps_extraction_capture  CHECK (capture_type IN ('SCREEN', 'PRINTOUT')),
    -- STUB 은 API 키 없이 백엔드·워커를 잇는 유일한 경로다. 빠뜨리면 stub 연동이 INSERT 에서 깨진다.
    CONSTRAINT ck_ps_extraction_pipeline CHECK (pipeline IN ('OCR_PIPELINE', 'VLM', 'STUB')),
    -- PARTIAL 을 FAILED 로 접지 않는다(20.2) — 쓸 수 있는 결과를 버리게 된다.
    CONSTRAINT ck_ps_extraction_status   CHECK (status IN ('COMPLETED', 'PARTIAL')),
    CONSTRAINT ck_ps_extraction_period   CHECK (period_source IS NULL OR period_source = 'HEADER')
);

CREATE INDEX ix_ps_extraction_business ON core.product_sales_extraction (business_id, created_at DESC);


-- =============================================================================
-- 2. PRODUCT_SALES_PERIOD — 기간·상품별 집계 (ERD §1.9, 합의 ①·②·⑤)
-- =============================================================================

CREATE TABLE core.product_sales_period (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT       NOT NULL,
    -- 어느 추출에서 왔나. 수기 입력(MANUAL)이면 null.
    extraction_id   BIGINT,
    period_start    DATE         NOT NULL,
    period_end      DATE         NOT NULL,

    product_name    VARCHAR(255) NOT NULL,     -- 인쇄된 원문. 화면 표시용
    -- ⑥ 백엔드가 정규화해 만든다. UK 를 가진 쪽이 만들어야 upsert 가 성립하고,
    --    규칙이 워커·서버 두 곳에 살면 반드시 갈라진다. 워커는 productName 원문만 보낸다.
    --    규칙(ERD §1.9): NFKC · 공백 제거 · 대소문자 통일 · 괄호 보존
    --    — `아메리카노(HOT)` 과 `(ICE)` 가 같아지면 안 된다.
    product_key     VARCHAR(255) NOT NULL,

    -- ② ERD 의 INT NOT NULL 을 내렸다. 라벨 1,059행에서 위반이 0건이지만 그 수치는
    --    근거가 못 된다 — 합성 생성기가 세 레이아웃 모두에 수량 열을 넣도록 만들어졌다.
    --    계약(ProductSalesRow.quantity)은 float|None 이라 수량 열이 없는 인쇄물이 오면
    --    NOT NULL 에서 그 행이 조용히 죽는다. 구성비는 금액으로 만들므로 잃는 것이 없다.
    --    NUMERIC 인 것은 무게 단위 상품(정육·반찬) 때문이다.
    quantity        NUMERIC(14, 3),

    -- ① ERD 의 NOT NULL 을 내렸다. 58mm 감열지에는 이 열이 인쇄되지 않는다 —
    --    실측 90표본 중 30표본 전부·행 353/1,059(33.3%)가 null 이다. 그대로 두면
    --    세 레이아웃 중 하나가 통째로 반려된다. ERD 가 discount·net·vat·billed 를
    --    Optional 로 내린 이유("8열이 감열지에 안 들어간다")에서 gross 만 빠져 있었다.
    gross_amount    NUMERIC(14, 2),
    discount_amount NUMERIC(14, 2),
    net_amount      NUMERIC(14, 2),
    -- 세무 계산에 쓰지 않는다(ERD). 부가세 예수금은 과세 매출 입금의 10/110 한 방식만 유지한다.
    vat_amount      NUMERIC(14, 2),
    -- 있으면 구성비의 기준. 58mm 에서 살아남는 금액 열이 이것이다.
    billed_amount   NUMERIC(14, 2),

    source_type     VARCHAR(16)  NOT NULL,     -- OCR · OCR_CORRECTED · MANUAL
    checksum_status VARCHAR(12)  NOT NULL,     -- MATCHED · MISMATCHED · UNAVAILABLE
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_ps_period_business   FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT fk_ps_period_extraction FOREIGN KEY (extraction_id)
        REFERENCES core.product_sales_extraction (id) ON DELETE SET NULL,
    -- 같은 기간 재등록은 upsert 로 갱신한다(14.4) — 오입력 정정이 잦아 409 를 내지 않는다.
    CONSTRAINT uk_ps_period UNIQUE (business_id, period_start, period_end, product_key),
    CONSTRAINT ck_ps_period_source   CHECK (source_type IN ('OCR', 'OCR_CORRECTED', 'MANUAL')),
    CONSTRAINT ck_ps_period_checksum
        CHECK (checksum_status IN ('MATCHED', 'MISMATCHED', 'UNAVAILABLE')),
    CONSTRAINT ck_ps_period_range    CHECK (period_end >= period_start),
    -- ① 이 테이블의 존재 이유가 구성비다. 진짜 지켜야 할 불변식은 "총매출이 있다"가 아니라
    --    "분모가 될 값이 하나는 있다"이다. ERD 자신도 분모를
    --    COALESCE(billed_amount, gross_amount) 로 정의해 이 경우를 전제하고 있다.
    --    실측 1,059행 전부 이 제약을 만족한다.
    CONSTRAINT ck_ps_period_share_basis
        CHECK (billed_amount IS NOT NULL OR gross_amount IS NOT NULL)
);

-- ⑤ share(구성비) 컬럼은 없다. ERD 결정("구성비는 조회 시 계산, 저장 없음")을 그대로 따른다 —
--   저장하면 billed_amount 와 share 두 곳에서 같은 사실이 관리되고 반드시 갈라진다.
--   워커가 보내는 인쇄된 구성비(열 정확도 95.0%, n=1,051)는 <대조용>이다. 우리 계산과 다르면
--   금액 오독이거나 분모 선택이 틀린 것이므로 로그로 남긴다.
--   ⚠ 이 값은 행 밀림을 잡지 못한다 — 구성비도 밀린 숫자 뭉치에 같이 실려 온다(실측 0/57).

-- 금액·수량에 > 0 CHECK 를 걸지 않는다. 집계 데이터라 취소·반품이 상계돼 음수가 될 수 있고,
-- TRANSACTION 의 amount > 0 을 복사하면 취소 데이터가 통째로 거부된다(ERD §1.9).

CREATE INDEX ix_ps_period_business ON core.product_sales_period (business_id, period_start);
