-- =============================================================================
-- BUSINESS_DAILY 패턴의 요일별 금액
--
-- 근거: docs/예측엔진_설계노트.md G-2 「금액 축」
--
-- 카드 정산은 주말·공휴일 매출이 다음 영업일로 몰려 들어와 **요일마다 금액이 다르다.**
-- 실측(하노식당 · 신한카드 124건 · 2026-04-01~09-23) — 아래는 이 마이그레이션과 같이
-- 들어가는 탐지기가 실제로 내는 값이다.
--
--     요일   표본        q10        q50        q90     q10~q90 폭
--     월     24      342,600    394,300    437,600       95,000
--     화     24      114,300    132,800    146,200       31,900
--     수     26      119,500    134,700    148,800       29,300
--     목     25      114,500    128,100    143,100       28,600
--     금     25      111,100    119,500    143,000       31,900
--
-- 월요일이 나머지의 3배다. 지금은 `expected_amount_min`/`max` 두 칸뿐이라 이것을
-- 범위 하나(110,600~582,100)로 뭉갠다. 그 결과 둘이 함께 망가진다.
--
--   · 중앙선   모든 요일에 같은 값을 써서 월요일은 모자라고 화~금은 과대하다
--   · 범위     하루 471,500원 폭이 30일(영업일 20)에 누적돼 밴드가 943만원까지 벌어진다.
--              요일별로 나누면 같은 20일이 867천원이다 — 91% 가 줄어든다
--
-- **nullable 이다.** 표본이 모자라거나 BUSINESS_DAILY 가 아니면 채우지 않고,
-- 그때는 지금처럼 `expected_amount_min`/`max` 를 쓴다. 컬럼 추가는
-- backend-architecture.md §5 의 허용 목록이라 롤백이 깨지지 않는다.
--
-- 값의 모양 — ISO 요일(1=월 … 7=일)을 키로, 분위수 셋을 담는다.
--
--     {"1": {"lo": 342600, "mid": 394300, "hi": 437600},
--      "2": {"lo": 114300, "mid": 132800, "hi": 146200}, ...}
--
-- **최소·최대가 아니라 q10/q90 이다.** 화요일 실측은 109,400~582,100 인데, 582,100 은
-- 연휴 뒤 한 건이다. 최대로 잡으면 그 하나가 화요일 폭 47만원을 혼자 만든다.
-- q90 이면 146,200 이고 폭은 31,900 이다.
-- =============================================================================
ALTER TABLE forecast.recurring_pattern ADD COLUMN amount_by_weekday JSONB;

COMMENT ON COLUMN forecast.recurring_pattern.amount_by_weekday IS
    'BUSINESS_DAILY 전용 요일별 금액 분위수. ISO 요일(1=월)을 키로 {lo,mid,hi}. '
    'null 이면 expected_amount_min/max 를 쓴다.';
