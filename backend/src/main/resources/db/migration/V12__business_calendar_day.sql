-- =============================================================================
-- 사업장 영업일 달력 (ERD BUSINESS_CALENDAR_DAY · 설계노트 G-2 ③)
--
-- **공휴일과 휴무일은 다르다.** 이 둘을 섞으면 곡선이 조용히 틀린다.
--
--     공휴일   은행·카드사가 쉰다        → 매출은 있고 정산만 다음 영업일로 밀린다
--     휴무일   가게가 문을 닫는다        → 매출 자체가 없다
--
-- 카페는 한글날·개천절·어린이날에 연다. 설날·추석만 닫는다. 앞은 정산이 이월되고
-- 뒤는 그 기간 매출이 사라지는데, 지금 백엔드는 **뒤를 모른다.**
--
-- 실측 (시드 「카페 한잔」 · 기준일 2026-09-13 · 30일):
--
--     예정 투영이 입금을 378,150원 과대평가한다. 그중 207,200원(55%)이 단 한 건이다 —
--     배달 정산 09-29 회차로, 그 주에 추석 휴업 사흘(9/24~26)이 들어 있다.
--     투영 497,400원 · 실제 290,200원.
--
--     곡선 공백 깊이로 보면 정답 −372,000원 대 예측 −57,398원이고,
--     그 오차 314,602원의 66%가 이 한 건에서 나온다.
--
-- **이력으로는 배울 수 없다.** 탐지 창(과거 180일)에 휴업일이 하나도 없다 — 설날은
-- 창보다 앞이고 추석은 뒤(예측 대상)다. 그 사이 공휴일에는 카페가 전부 영업했다.
-- 그래서 「금액이 영업일 수에 비례하는가」를 표본으로 검정하면 **신호가 없다**
-- (우아한형제들 26건: 영업일로 나누면 변동계수가 오히려 59% 악화).
--
-- 없는 데이터를 추정하는 대신 **아는 쪽이 등록한다.** 사장님은 자기 휴무일을 알고,
-- 시드 생성기는 자기 closedDays 를 안다.
--
-- =============================================================================

CREATE TABLE forecast.business_calendar_day (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- null 이면 공통 달력이다 (관공서 공휴일). 사업장별 행이 있으면 그쪽이 이긴다.
    business_id   BIGINT,
    calendar_date DATE         NOT NULL,
    day_type      VARCHAR(20)  NOT NULL,
    source        VARCHAR(20)  NOT NULL,
    name          VARCHAR(100),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_bcd_business FOREIGN KEY (business_id) REFERENCES core.business (id),
    CONSTRAINT ck_bcd_day_type CHECK (day_type IN ('BUSINESS_DAY', 'HOLIDAY', 'CLOSED')),
    CONSTRAINT ck_bcd_source   CHECK (source   IN ('USER', 'PUBLIC_API', 'SEED'))
);

-- UK 를 둘로 나눈 이유: 단일 인덱스 `(business_id, calendar_date)` 로는 공통 달력이
-- 안 막힌다. 포스트그레스는 NULL 을 서로 다른 값으로 보므로 같은 날짜의 공통 행이
-- 얼마든지 들어간다. 부분 인덱스 두 개라야 양쪽 다 하나씩으로 묶인다.
CREATE UNIQUE INDEX uk_bcd_business ON forecast.business_calendar_day (business_id, calendar_date)
    WHERE business_id IS NOT NULL;
CREATE UNIQUE INDEX uk_bcd_common ON forecast.business_calendar_day (calendar_date)
    WHERE business_id IS NULL;

-- 투영이 「이 기간에 며칠 쉬었나」를 세는 것이 유일한 읽기 경로다.
CREATE INDEX ix_bcd_lookup ON forecast.business_calendar_day (business_id, calendar_date, day_type);

COMMENT ON TABLE forecast.business_calendar_day IS
    '공휴일·휴무일. day_type = CLOSED 인 날은 가게가 닫아 매출이 없다 (공휴일과 다르다).';
COMMENT ON COLUMN forecast.business_calendar_day.business_id IS
    'null 이면 공통 달력. 사업장 행이 있으면 그쪽이 이긴다.';
