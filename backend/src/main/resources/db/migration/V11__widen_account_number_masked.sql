-- =============================================================================
-- ACCOUNT.account_number_masked — 담는 값 기준으로 다시 잡는다
--
-- V1 은 이 컬럼을 VARCHAR(32) 로 잡았다. 숫자만 남긴 계좌번호 기준의 크기다.
-- 그런데 실제로 들어가는 값은 마스킹 결과이고, 마스킹은 사용자가 친 구분자를
-- 그대로 보존한다(구현현황 3.7, 명세 7.2 예시 110-***-***789).
--
--   "0014123456789012"       (16자) -> 001**********012      16자
--   "0014-1234-5678-9012"    (19자) -> 001*-****-****-*012   19자
--
-- 즉 컬럼이 견뎌야 하는 길이는 계좌번호 자릿수가 아니라 <b>사용자 입력 길이</b>다.
-- V4 의 BUSINESS.registration_number 와 같은 종류의 어긋남이다 — 그때는 평문
-- 기준으로 잡은 컬럼에 암호문을 넣었고, 여기서는 숫자 기준으로 잡은 컬럼에
-- 구분자를 포함한 값을 넣는다.
--
-- 지금 500 이 나지는 않는다. LinkRequest.accountNo 의 @Size(max = 32) 가
-- 입력을 32자로 자르고 마스킹이 길이를 보존하므로 결과도 딱 32자를 넘지 않는다.
-- 여유가 0 이고 그 사실이 어디에도 적혀 있지 않다는 것이 문제다 — 입력 상한을
-- 올리는 순간(더 긴 계좌번호, 구분자 허용 확대) 조용히 아래가 된다. 실측:
--
--   ERROR: value too long for type character varying(32)
--
-- 64 는 입력 상한 32 의 두 배다. 구분자가 자릿수만큼 붙어도 들어간다.
--
-- V1 상단 마이그레이션 규칙 대조 — "타입 변경 금지"는 좁히는 방향을 막는 규칙이며
-- VARCHAR 를 넓히면 구버전 코드가 쓰던 값이 그대로 들어가므로 롤백이 깨지지 않는다
-- (V4 에서 같은 판단을 했다).
-- =============================================================================

ALTER TABLE core.account
    ALTER COLUMN account_number_masked TYPE VARCHAR(64);
