package com.jangoyebo.forecast.planned;

/**
 * 예정 거래 자동 반영 원장의 상태 (API 9.6).
 *
 * <p>예정 거래 자신의 {@link PlannedStatus} 와 <b>다른 축이다.</b> 저쪽은 「이 예정 거래가
 * 실제로 일어났나」를 말하고, 이쪽은 「우리가 금융망에 보냈나」를 말한다. 둘이 갈리는
 * 구간이 있다 — 보냈지만 아직 동기화되지 않았으면 원장은 {@link #EXECUTED} 인데 예정 거래는
 * 여전히 {@code EXPECTED} 다.
 */
public enum PlannedExecutionStatus {

    /**
     * 보냈거나, 보내는 중에 답을 못 받았다.
     *
     * <p><b>호출 직전에 커밋한다.</b> 이 표시가 없으면 응답을 기다리다 죽었을 때 다음 차례가
     * 「보낸 적 없다」로 읽고 또 보낸다. 다음 차례는 이 상태를 보고 <b>금융망 거래내역부터
     * 확인한다.</b>
     */
    SENT,

    /** 금융망에 실제로 반영됐다. 동기화가 그 거래를 가져오면 {@link #MATCHED} 로 간다. */
    EXECUTED,

    /** 가져온 거래를 예정 거래에 정확히 붙였다. 이 원장 행의 종착점이다. */
    MATCHED,

    /**
     * 실패했다. {@code retryAfter} 가 있으면 그날 이후 다시 시도하고, 없으면 영구 실패다.
     *
     * <p>잔액 부족({@code A1014})이 대표적인 재시도 대상이다 — <b>결함이 아니라 사건</b>이라
     * 다음 날 다시 시도한다.
     */
    FAILED,

    /** 보낼 수 없는 것이었다(금액이 1원 미만 등). 다시 집지 않는다. */
    SKIPPED
}
