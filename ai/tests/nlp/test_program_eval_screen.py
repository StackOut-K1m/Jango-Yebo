"""공고 평가 선별기 — **멀쩡한 값을 환각 후보로 몰지 않는가** (`-94`).

2026-09-16 첫 유료 실행에서 근거 없는 값이 11개 나왔는데, **그중 6개가 선별기 탓**이었다.
값은 원문에 그대로 있는데 표기가 한 글자 달라 못 찾은 것들이다.

| 놓친 값 | 원문 | 왜 |
| --- | --- | --- |
| `휴·폐업체` | `휴ㆍ폐업체 제외` | 가운뎃점이 다른 글자다 (U+00B7 vs U+318D) |
| `10000000` | `1,000만원` | 한글 단위 앞에도 천 단위 쉼표가 온다 |
| `250000000` | `2억 5천만원` | 억으로 나누어떨어지지 않아 억 표기를 안 만들었다 |
| `제조업` | `중소 제조기업` | 꼬리말이 다르다 |
| `경기 안양시` | `[경기] 안양시 …` | 두 토막을 붙여 적었다 |
| 제외 문장 | 자격 문장을 뒤집은 것 | 「이력이 없는 기업」 → 「이력이 있는 기업」 |

**이건 모델 품질이 아니라 자의 눈금 문제다.** 눈금이 틀리면 두 갈래로 해롭다 — 사람이
읽어야 할 목록이 오탐으로 차서 **진짜 환각이 묻히고**, 통과 기준(근거 없는 값 0)은
영영 못 넘어 판정 자체가 무의미해진다.

여기 있는 문자열은 전부 **실제 공고에서 그대로 가져온 것**이다. 지어낸 예로 재면
같은 실패가 또 지나간다.
"""

from __future__ import annotations

import pytest

from evals.run_program_eval import _number_supported, _text_supported

# ------------------------------------------------------------------ 숫자 표기


@pytest.mark.parametrize(
    ("value", "hay"),
    [
        # g25 — 한글 단위 앞의 천 단위 쉼표
        (10_000_000, "생산ㆍ근로환경 개선 비용 80% 지원(기업당 최대 1,000만원 지원)"),
        # g12 — 억으로 나누어떨어지지 않는 복합 표기
        (250_000_000, "2025년 연매출액(부가세 포함) 2억 5천만원 이하 울산 중구 소상공인"),
        # 원래도 통하던 것들 — 고치면서 깨지지 않았는지 본다
        (300_000_000, "연매출 3억원 미만 소상공인"),
        (300_000, "최대 30만원 지원"),
        (5_000_000, "업체당 최대 500만원"),
        (104_000_000, "연매출 1억 4백만원 미만"),
    ],
)
def test_원문에_있는_금액을_찾아낸다(value: int, hay: str) -> None:
    assert _number_supported(value, hay)


@pytest.mark.parametrize(
    ("value", "hay"),
    [
        # g10 — 「월 30만원 × 6개월」을 곱해 만든 총액. 원문에 이 수는 없다.
        (1_800_000, "사업장 임차료 월 30만 원 한도, 최대 6개월간 지원"),
        (99_999, "최대 30만원 지원"),
    ],
)
def test_원문에_없는_금액은_걸러_낸다(value: int, hay: str) -> None:
    """**이쪽이 느슨해지면 자가 망가진다.** 곱해서 만든 수를 통과시키면 안 된다."""
    assert not _number_supported(value, hay)


# ------------------------------------------------------------------ 글자 표기


@pytest.mark.parametrize(
    ("value", "hay"),
    [
        # g16 — 가운뎃점 두 벌. 모델은 U+00B7, 공고는 U+318D 를 쓴다.
        ("휴·폐업체", "- 사업자등록 후 1년 이상 영업 중인 업체 (휴ㆍ폐업체 제외)"),
        # g07 — 꼬리말만 다르다
        ("제조업", "☞ 충청남도 소재 중소 제조기업"),
        # g16 — 두 토막을 붙여 적었다
        ("경기 안양시", "[경기] 안양시 2026년 현장노동자 휴게시설 개선사업 모집 공고"),
        # g16 (2차) — 가운뎃점 축약을 푼 값. 공고는 줄여 쓰고 모델은 항목으로 편다.
        ("휴업체", "- 사업자등록 후 1년 이상 영업 중인 업체 (휴ㆍ폐업체 제외)"),
        ("폐업체", "- 사업자등록 후 1년 이상 영업 중인 업체 (휴ㆍ폐업체 제외)"),
        ("생산환경", "사업장 생산ㆍ근로환경 개선을 위한 비용 80% 지원"),
        # g05 — 자격 문장을 제외 항목으로 뒤집었다. 뿌리는 원문에 있다.
        (
            "인턴 시작일 기준 3개월전까지 권고사직 이력이 있는 기업",
            "- 인턴 시작일 기준 3개월전까지 권고사직 이력이 없는 기업"
            " (인턴 사업 최초 참여 사업장의 경우 1개월 이력 확인)",
        ),
    ],
)
def test_표기가_달라도_원문에_뿌리가_있으면_통과한다(value: str, hay: str) -> None:
    assert _text_supported(value, hay)


@pytest.mark.parametrize(
    ("value", "hay"),
    [
        # 프롬프트가 「명시된 경우에만」으로 바뀌었다. 지역 이야기가 없는 공고에
        # 「전국」을 적으면 제한이 없다고 **단정한** 것이라 걸러야 한다.
        ("전국", "☞ 충청남도 소재 중소 제조기업"),
        ("전 업종", "☞ 현장노동자가 이용하는 열악한 휴게시설의 개선이 필요한 관내 중소제조업체"),
        # 원문 어디에도 뿌리가 없는 조건
        ("국세 체납자", "☞ 사업장 임차료 월 30만 원 한도, 최대 6개월간 지원"),
    ],
)
def test_원문에_뿌리가_없으면_걸러_낸다(value: str, hay: str) -> None:
    assert not _text_supported(value, hay)


def test_너무_짧은_값은_판단하지_않는다() -> None:
    """한두 글자는 우연히 맞거나 우연히 안 맞는다. 사람에게 넘길 근거가 못 된다."""
    assert _text_supported("무", "아무 상관 없는 문장")
