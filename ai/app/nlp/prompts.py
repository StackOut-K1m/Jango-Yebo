def _transaction_line(tx: TransactionToClassify) -> str:
    parts = [
        f"transactionId={tx.transaction_id}",
        f"적요={tx.description!r}",
        f"방향={tx.direction}",
        f"금액={tx.amount}",
        f"발생={tx.occurred_at.isoformat()}",
    ]
    if tx.cycle_hint:
        # P0-03 반복 탐지가 계산한 값이다. 모델이 주기를 추론하는 것보다 정확하고 싸다 (§6.3)
        parts.append(f"주기={tx.cycle_hint}")
    return " | ".join(parts)


def _few_shot_line(example: FewShotExample) -> str:
    merchant = example.merchant_name or "-"
    return (
        f"적요={example.description!r} | 방향={example.direction}"
        f" → {example.category} (거래처: {merchant})"
    )


def classification_user_text(
    *,
    industry_type: str,
    allowed_categories: list[str],
    few_shot_examples: list[FewShotExample],
    transactions: list[TransactionToClassify],
) -> str:
    """사용자 메시지. 캐시가 잘 듣도록 변동이 적은 것부터 쌓는다.

    업종·허용 카테고리(사업장 단위로 고정) → few-shot(하루 1회) → 거래 목록(매 요청).
    """
    blocks = [
        f"업종: {industry_type}",
        "허용 카테고리 (이 안에서만 고른다):\n" + ", ".join(allowed_categories),
    ]
    if few_shot_examples:
        lines = "\n".join(_few_shot_line(example) for example in few_shot_examples)
        blocks.append(
            "이 사업장에서 사용자가 직접 정정한 이력이다. 같은 적요가 또 나오면 이대로 따른다:\n"
            + lines
        )
    lines = "\n".join(_transaction_line(tx) for tx in transactions)
    blocks.append(f"분류할 거래 {len(transactions)}건:\n{lines}")
    blocks.append("각 거래를 스키마대로 분류해 반환하라.")
    return "\n\n".join(blocks)


